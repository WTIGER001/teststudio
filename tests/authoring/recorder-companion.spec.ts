import { test, expect } from '@playwright/test'

test.use({ actionTimeout: 10000, navigationTimeout: 15000 })

test('Connect a desktop recorder, retain captured source, and save a reviewed draft', { tag: '@STUDIO-COMPANION-001' }, async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.context().addCookies([FIXTURE_SESSION_COOKIE])
  await page.goto('/projects/beta/tests/new/playwright')
  await page.getByLabel('Suite for this test', { exact: true }).selectOption('health')
  const recorder = page.getByRole('region', { name: 'Record a browser test', exact: true })
  const progress = recorder.getByRole('navigation', { name: 'Browser recording progress', exact: true })
  await expect(progress.locator('[aria-current="step"]')).toContainText('Configure')
  await expect(recorder.getByLabel('Recorded test ID', { exact: true })).not.toBeVisible()
  await recorder.getByLabel('Recorded test title', { exact: true }).fill('Desktop recorded navigation')
  await recorder.getByLabel('Recording start address', { exact: true }).fill(FIXTURE_TARGET_URL)
  await expect(page.getByLabel('Suite for this test', { exact: true })).toBeDisabled()
  await recorder.getByText('Advanced recording details', { exact: true }).click()
  await recorder.getByLabel('Recorded test ID', { exact: true }).fill('REC-HOSTED-001')
  await recorder.getByRole('button', { name: 'Continue to desktop connection', exact: true }).click()
  await expect(progress.locator('[aria-current="step"]')).toContainText('Connect desktop')
  await expect(recorder.getByRole('heading', { name: 'Connect your desktop recorder', exact: true })).toBeFocused()
  const code = recorder.getByLabel('Connection code', { exact: true })
  const first = await code.inputValue()
  expect(first.length > 43).toBe(true)
  await recorder.getByRole('button', { name: 'Get new connection code', exact: true }).click()
  await expect.poll(async () => (await code.inputValue()) !== first).toBe(true)
  const rotated = await code.inputValue()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Create test help', exact: true })
  await expect(help.getByText('Desktop connection', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  expect((await code.inputValue()) === rotated).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme', { exact: true }).selectOption('dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('desktop-connection-dark-mobile', { body: await page.screenshot({ fullPage: true, mask: [code] }), contentType: 'image/png' })
  await page.reload()
  await page.getByLabel('Suite for this test', { exact: true }).selectOption('health')
  await expect(progress.locator('[aria-current="step"]')).toContainText('Connect desktop')
  await expect(code).toHaveCount(0)
  await recorder.getByRole('button', { name: 'Get new connection code', exact: true }).click()
  const connectionCode = await code.inputValue()
  const session = await (await page.request.get('/auth/session')).json()
  const connected = await page.request.post('/verification/companion', { data: { code: connectionCode }, headers: { Origin: new URL(page.url()).origin, 'X-CSRF-Token': session.session.csrfToken } })
  expect(connected.status()).toBe(202)
  await expect(recorder.getByRole('status').filter({ hasText: /^Recording ·/ })).toBeVisible({ timeout: 20000 })
  await expect(code).toHaveCount(0)
  await expect(progress.locator('[aria-current="step"]')).toContainText('Record')
  const base = '/api/v1/projects/beta/suites/health/browser-recordings'
  await expect.poll(async () => {
    const history = await (await page.request.get(base)).json()
    return history.items.some((row: any) => row.data.testId === 'REC-HOSTED-001' && row.data.code?.includes('page.goto('))
  }, { timeout: 20000 }).toBe(true)
  await recorder.getByRole('button', { name: 'Stop and keep recording', exact: true }).click()
  await expect(recorder.getByRole('status').filter({ hasText: 'Ready for review' })).toBeVisible({ timeout: 15000 })
  await expect(progress.locator('[aria-current="step"]')).toContainText('Review')
  await expect(recorder.getByRole('heading', { name: 'Review the captured test', exact: true })).toBeFocused()
  await recorder.getByRole('button', { name: 'Review recorded test', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Playwright editor', exact: true })
  await expect(editor.getByRole('textbox', { name: 'Source code: checks/recording.spec.ts', exact: true })).toContainText('@REC-HOSTED-001')
  await expect(editor.getByRole('textbox', { name: 'Source code: checks/recording.spec.ts', exact: true })).toContainText('TESTSTUDIO_BASE_URL')
  await editor.getByRole('button', { name: 'Save Playwright draft', exact: true }).click()
  await expect(editor.getByRole('status').filter({ hasText: 'Draft saved at revision 1.' })).toBeVisible()
  expect((await (await page.request.get('/api/v1/projects/beta/runs')).json()).items).toEqual([])
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Color theme', { exact: true }).selectOption('light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('desktop-recording-reviewed-light', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await recorder.getByRole('button', { name: 'New recording', exact: true }).click()
  await expect(progress.locator('[aria-current="step"]')).toContainText('Configure')
  await expect(recorder.getByLabel('Recording start address', { exact: true })).toHaveValue(FIXTURE_TARGET_URL)
  await recorder.getByText('Advanced recording details', { exact: true }).click()
  expect((await recorder.getByLabel('Recorded test ID', { exact: true }).inputValue()) !== 'REC-HOSTED-001').toBe(true)
  expect(errors).toEqual([])
})
