import { test, expect } from '@playwright/test'

test.use({ actionTimeout: 10000, navigationTimeout: 15000 })

test('Record News and a visible story inside TestStudio without desktop setup', { tag: '@STUDIO-EMBEDDED-RECORDER-001' }, async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.context().addCookies([FIXTURE_SESSION_COOKIE])
  await page.goto('/projects/beta/tests/new/playwright?suite=health')
  const recorder = page.getByRole('region', { name: 'Record a browser test', exact: true })
  for (const [width, theme] of [[1280, 'light'], [900, 'dark'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.getByLabel('Color theme', { exact: true }).selectOption(theme)
    const title = await recorder.getByLabel('Recorded test title', { exact: true }).boundingBox()
    const address = await recorder.getByLabel('Recording start address', { exact: true }).boundingBox()
    const hint = await recorder.getByLabel('Recording start address', { exact: true }).locator('..').locator('small').boundingBox()
    if (!title || !address || !hint) throw new Error('Recording fields or description are missing')
    expect(Math.abs(title.height - address.height)).toBeLessThan(1)
    expect(title.height).toBeLessThan(45)
    if (width > 700) expect(Math.abs(title.y - address.y)).toBeLessThan(1)
    else expect(address.y).toBeGreaterThanOrEqual(title.y + title.height)
    expect(hint.y).toBeGreaterThanOrEqual(address.y + address.height)
    if (width === 900) expect(hint.height).toBeGreaterThan(25)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await testInfo.attach(`recording-fields-${width}-${theme}`, { body: await recorder.screenshot(), contentType: 'image/png' })
  }
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.getByLabel('Color theme', { exact: true }).selectOption('light')
  await recorder.getByLabel('Recorded test title', { exact: true }).fill('News lists stories')
  await recorder.getByLabel('Recording start address', { exact: true }).fill(FIXTURE_TARGET_URL)
  await page.route('**/browser-recordings', async route => { if (route.request().method() === 'POST') { const response = await route.fetch(); await new Promise(resolve => setTimeout(resolve, 750)); await route.fulfill({ response }) } else await route.continue() }, { times: 1 })
  await recorder.getByRole('button', { name: 'Start recording', exact: true }).click()
  const live = recorder.getByRole('region', { name: 'Live recording browser', exact: true })
  const browser = live.getByRole('group', { name: 'Recording browser', exact: true })
  await expect(browser).toBeVisible({ timeout: 20000 })
  await expect(recorder.getByLabel('Connection code', { exact: true })).toHaveCount(0)
  await expect(recorder.getByLabel('Desktop recorder command', { exact: true })).toHaveCount(0)
  async function clickWebsite(x: number, y: number) {
    const bounds = await browser.boundingBox()
    if (!bounds) throw new Error('The recording browser is missing')
    await browser.click({ position: { x: 2 + x * (bounds.width - 4) / Number(await browser.getAttribute('width')), y: 2 + y * (bounds.height - 4) / Number(await browser.getAttribute('height')) } })
  }
  await expect.poll(async () => (await (await page.request.get('/_fixture/recording-ready')).json()).loaded).toBeGreaterThanOrEqual(1)
  await clickWebsite(35, 25)
  await expect(live.locator('.browser-address')).toHaveText(FIXTURE_TARGET_URL + '/news')
  await expect(live.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('Click “News”')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Create test help', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(browser).toBeVisible()
  await expect.poll(async () => (await (await page.request.get('/_fixture/recording-ready')).json()).loaded).toBeGreaterThanOrEqual(2)
  await live.getByRole('button', { name: 'Check something appears', exact: true }).click()
  await expect(live.getByRole('status')).toContainText('Click the item that should appear')
  await clickWebsite(120, 85)
  await expect(live.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('Check “Regional harvest begins” is visible')
  await live.getByRole('button', { name: 'Open recording dialog', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Recording workspace', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByText('Browser window size', { exact: true }).click()
  await dialog.getByLabel('Window preset', { exact: true }).selectOption('390x844')
  await expect(dialog.getByRole('group', { name: 'Recording browser', exact: true })).toHaveAttribute('width', '390')
  await expect(dialog.getByRole('group', { name: 'Recording browser', exact: true })).toHaveAttribute('height', '844')
  await testInfo.attach('recording-dialog-phone', { body: await dialog.screenshot(), contentType: 'image/png' })
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(live.getByRole('button', { name: 'Open recording dialog', exact: true })).toBeFocused()
  await live.getByText('Browser window size', { exact: true }).click()
  await live.getByLabel('Browser width (pixels)', { exact: true }).fill('319')
  await live.getByRole('button', { name: 'Apply browser size', exact: true }).click()
  await expect(live.getByRole('alert')).toContainText('width 320–1920')
  await live.getByLabel('Browser width (pixels)', { exact: true }).fill('800')
  await live.getByLabel('Browser height (pixels)', { exact: true }).fill('600')
  await live.getByRole('button', { name: 'Apply browser size', exact: true }).click()
  await expect(browser).toHaveAttribute('width', '800')
  await expect(browser).toHaveAttribute('height', '600')
  const popupPromise = page.waitForEvent('popup')
  await live.getByRole('button', { name: 'Open recording in new tab', exact: true }).click()
  const popup = await popupPromise
  popup.on('pageerror', error => errors.push(error.message))
  try {
    await expect(popup.getByRole('heading', { name: 'Recording workspace', exact: true })).toBeVisible()
    const work = popup.getByRole('region', { name: 'Live recording browser', exact: true })
    const remote = work.getByRole('group', { name: 'Recording browser', exact: true })
    await expect(remote).toHaveAttribute('width', '800')
    await expect(recorder.getByRole('button', { name: 'Finish recording', exact: true })).toBeDisabled()
    await expect(live.getByRole('status')).toContainText('another tab')
    await popup.getByRole('button', { name: 'Help', exact: true }).click()
    await expect(popup.getByRole('dialog', { name: 'Create test help', exact: true })).toBeVisible()
    await popup.keyboard.press('Escape')
    async function chooseStory() {
      await work.getByRole('button', { name: 'Check count or text', exact: true }).click()
      await expect(work.getByRole('status')).toContainText('Click a story')
      const bounds = await remote.boundingBox()
      if (!bounds) throw new Error('The separate-tab browser is missing')
      await remote.click({ position: { x: 2 + 120 * (bounds.width - 4) / 800, y: 2 + 85 * (bounds.height - 4) / 600 } })
      await expect(work.getByRole('region', { name: 'Review new check', exact: true })).toContainText('2 matching items')
    }
    await chooseStory()
    await work.getByRole('button', { name: 'Add check', exact: true }).click()
    await expect(work.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('at least 1')
    await chooseStory()
    await work.getByLabel('Check type', { exact: true }).selectOption('exactly')
    await work.getByLabel('Expected item count', { exact: true }).fill('3')
    await work.getByRole('button', { name: 'Add check', exact: true }).click()
    await expect(work.getByRole('region', { name: 'Review new check', exact: true })).toContainText('There are 2 matching items now')
    await work.getByLabel('Expected item count', { exact: true }).fill('2')
    await work.getByRole('button', { name: 'Add check', exact: true }).click()
    await expect(work.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('exactly 2')
    await chooseStory()
    await work.getByLabel('Check type', { exact: true }).selectOption('text')
    await work.getByLabel('Expected text', { exact: true }).fill('Regional harvest')
    await work.getByRole('button', { name: 'Add check', exact: true }).click()
    await expect(work.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('contains “Regional harvest”')
    await work.getByRole('button', { name: 'Check page address', exact: true }).click()
    await expect(work.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('Check the current page address')
    await testInfo.attach('recording-separate-tab-checks', { body: await popup.screenshot({ fullPage: true }), contentType: 'image/png' })
    await live.getByRole('button', { name: 'Control recording here', exact: true }).click()
    await expect(work.getByRole('button', { name: 'Control recording here', exact: true })).toBeVisible()
  } finally { await popup.close() }
  await expect(browser).toHaveAttribute('width', '800')
  await expect(live.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('exactly 2')
  const capturedStepCount = await live.getByRole('list', { name: 'Captured steps', exact: true }).getByRole('listitem').count()
  await page.route('**/browser-recordings/*/input', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'The browser connection was interrupted.' }) }), { times: 1 })
  await live.getByRole('button', { name: 'Scroll down', exact: true }).click()
  await expect(live.getByRole('alert')).toContainText('Actions are not repeated automatically')
  await expect(live.getByRole('button', { name: 'Check something appears', exact: true })).toBeDisabled()
  await recorder.getByRole('button', { name: 'Refresh recording', exact: true }).click()
  await expect(live.getByRole('button', { name: 'Check something appears', exact: true })).toBeDisabled()
  await live.getByRole('button', { name: 'Refresh browser view', exact: true }).click()
  await expect(live.getByRole('alert')).toHaveCount(0)
  await expect(live.getByRole('list', { name: 'Captured steps', exact: true }).getByRole('listitem')).toHaveCount(capturedStepCount)
  await testInfo.attach('embedded-news-recording', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await page.reload()
  await expect(browser).toHaveAttribute('width', '800')
  await expect(browser).toBeVisible({ timeout: 15000 })
  await expect(live.getByRole('list', { name: 'Captured steps', exact: true })).toContainText('Check “Regional harvest begins” is visible')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme', { exact: true }).selectOption('dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await browser.focus()
  await expect(browser).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(live.getByRole('button', { name: 'Scroll up', exact: true })).toBeFocused()
  await testInfo.attach('embedded-news-dark-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await recorder.getByRole('button', { name: 'Finish recording', exact: true }).click()
  await expect(recorder.getByRole('list', { name: 'Recorded test steps', exact: true })).toContainText('Check “Regional harvest begins” is visible')
  await expect(browser).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Source code: checks/recording.spec.ts', exact: true })).not.toBeVisible()
  let dropSaveConfirmation = true
  await page.route('**/playwright-drafts/*', async route => {
    if (route.request().method() === 'PUT' && dropSaveConfirmation) {
      dropSaveConfirmation = false
      const saved = await route.fetch()
      expect(saved.status()).toBe(200)
      await route.abort('failed')
    } else await route.continue()
  })
  await recorder.getByRole('button', { name: 'Save test draft', exact: true }).click()
  await expect(recorder.getByRole('status').filter({ hasText: 'Test draft saved.' })).toBeVisible()
  await recorder.getByRole('button', { name: 'Advanced: review source', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Source code: checks/recording.spec.ts', exact: true })).toContainText('toBeVisible()')
  await page.getByText('Advanced source editing', { exact: true }).click()
  await page.reload()
  await recorder.getByText('Your recording history', { exact: true }).click()
  await recorder.getByRole('button', { name: 'News lists stories · Ready for review', exact: true }).click()
  await recorder.getByRole('button', { name: 'Save test draft', exact: true }).click()
  await expect(recorder.getByRole('status').filter({ hasText: 'Test draft saved.' })).toBeVisible()
  await expect(recorder.getByRole('region', { name: 'Next step for saved recording', exact: true })).toBeVisible()
  await recorder.getByRole('button', { name: 'Prepare saved test', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Suite preparation', exact: true })).toBeFocused()
  await expect(recorder.getByRole('status').filter({ hasText: 'Revision 1 queued.' })).toBeVisible()
  const drafts = await (await page.request.get('/api/v1/projects/beta/suites/health/playwright-drafts')).json()
  expect(drafts.items).toHaveLength(1)
  expect(drafts.items[0].revision).toBe(1)
  const savedSource = drafts.items[0].data.files.find((file: { path: string }) => file.path === 'checks/recording.spec.ts').content
  for (const expected of ['toBeGreaterThanOrEqual(1)', 'toHaveCount(2)', 'toContainText(\"Regional harvest\")', 'toHaveURL(', 'setViewportSize({ width: 800, height: 600 })']) expect(savedSource).toContain(expected)
  expect(savedSource).not.toContain('teststudio_')
  expect((await (await page.request.get('/api/v1/projects/beta/runs')).json()).items).toEqual([])
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Color theme', { exact: true }).selectOption('light')
  await testInfo.attach('embedded-news-saved', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await recorder.getByRole('button', { name: 'New recording', exact: true }).click()
  await recorder.getByRole('button', { name: 'Start recording', exact: true }).click()
  await expect(browser).toBeVisible({ timeout: 15000 })
  await recorder.getByRole('button', { name: 'Cancel recording', exact: true }).click()
  await expect(browser).toHaveCount(0)
  await expect(recorder.getByRole('status').filter({ hasText: /^Cancelled ·/ })).toBeVisible()
  expect(errors).toEqual([])
})
