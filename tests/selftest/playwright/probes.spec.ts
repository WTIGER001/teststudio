test('Nine generic probes save without execution and recover partial rows', {tag:'@STUDIO-PROBE-SETUP-001'},async({page,api})=>{
 const {project,path}=await api.scaffold()
 await page.goto(`/projects/${project}/probes/new`)
 const urls=['production','beta','development'].flatMap(stage=>['www','admin','search'].map(surface=>`https://${surface}.${stage}.example.com/`))
 await page.getByLabel('Website URLs',{exact:true}).fill(urls.join('\n'))
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 for(let i=0;i<9;i++)await page.getByLabel(`Stage ${i+1}`,{exact:true}).selectOption(['production','beta','development'][Math.floor(i/3)])
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 let failed=false
 await page.route(`**${path}/probes`,async route=>{
  if(route.request().method()==='POST'&&!failed){failed=true;await route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({message:'Controlled partial save'})})}else await route.continue()
 })
 await expectHTTPFailure(page,'POST',`${path}/probes`,422,()=>page.getByRole('button',{name:'Save probe configuration',exact:true}).click())
 await expect(page.getByRole('button',{name:'Retry unfinished rows',exact:true})).toBeEnabled()
 await page.getByRole('button',{name:'Retry unfinished rows',exact:true}).click()
 await expect(page.getByRole('button',{name:'Open HTTPS probes',exact:true})).toBeVisible()
 expect((await api.call('GET',`${path}/probes`)).matched).toBe(9)
 expect((await api.call('GET',`${path}/tests`)).items).toHaveLength(9)
 expect((await api.call('GET',`${path}/environments`)).items).toHaveLength(10)
 expect((await api.call('GET',`${path}/runs`)).items).toHaveLength(0)
 expect((await api.call('GET',`${path}/schedules`)).items).toHaveLength(0)
 await page.getByRole('button',{name:'Open HTTPS probes',exact:true}).click()
 await expect(page.getByRole('article')).toHaveCount(9)
 const existing=(await api.call('GET',`${path}/probes`)).items[0]
 await page.getByRole('link',{name:'Add existing check',exact:true}).click()
 await page.getByLabel('Existing native check',{exact:true}).selectOption(existing.testId)
 await page.getByLabel('Target environment',{exact:true}).selectOption(existing.environmentId)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Save probe configuration',exact:true}).click()
 await expect(page.getByRole('button',{name:'Open HTTPS probes',exact:true})).toBeVisible()
 expect((await api.call('GET',`${path}/probes`)).matched).toBe(9)
})

test('Reviewed bulk probe actions retain completed runs during a partial retry', {tag:'@STUDIO-PROBE-BULK-001'},async({page,api})=>{
 const {project,path}=await api.scaffold();await api.createCheck(path)
 await bind(api,path,'First target')
 await api.call('PUT',`${path}/environments/other`,{id:'other',name:'Other target',applicationId:'app',stage:'local',endpoints:{api:'http://127.0.0.1:8040'}},0)
 await bind(api,path,'Second target','SELF-CHECK','other')
 await page.goto(`/projects/${project}/probes`)
 await page.getByRole('checkbox',{name:'Select First target',exact:true}).check()
 await page.getByRole('checkbox',{name:'Select Second target',exact:true}).check()
 await page.getByRole('button',{name:'Review selected runs',exact:true}).click()
 const review=page.getByRole('region',{name:'Review selected probe actions'})
 await expect(review.getByRole('button',{name:'Apply or retry selected actions',exact:true})).toBeEnabled()
 let requests=0
 await page.route(`**${path}/runs`,async route=>{
  if(route.request().method()==='POST'&&++requests===1)await route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({message:'Controlled partial run creation'})})
  else await route.continue()
 })
 await expectHTTPFailure(page,'POST',`${path}/runs`,422,()=>review.getByRole('button',{name:'Apply or retry selected actions',exact:true}).click())
 await expect(review.getByRole('link',{name:'Inspect created run',exact:true})).toHaveCount(1)
 await review.getByRole('button',{name:'Close review',exact:true}).click()
 await page.getByRole('button',{name:'Review selected runs',exact:true}).click()
 await expect(review.getByRole('link',{name:'Inspect created run',exact:true})).toHaveCount(1)
 await review.getByRole('button',{name:'Apply or retry selected actions',exact:true}).click()
 await expect(review.getByRole('link',{name:'Inspect created run',exact:true})).toHaveCount(2)
 expect((await api.call('GET',`${path}/runs`)).items).toHaveLength(2)
 await review.getByRole('button',{name:'Close review',exact:true}).click()
 await page.getByRole('checkbox',{name:'Select First target',exact:true}).check()
 await page.getByRole('checkbox',{name:'Select Second target',exact:true}).check()
 await page.getByRole('button',{name:'Review selected archival',exact:true}).click()
 await expect(review).toContainText('Pause schedules separately')
 const first=(await api.call('GET',`${path}/probes`)).items.find((p:any)=>p.name==='First target')
 let lost=false
 await page.route(`**${path}/probes/${first.id}`,async route=>{
  if(route.request().method()==='PUT'&&!lost){lost=true;await route.fetch();await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'Controlled lost archive acknowledgement'})})}else await route.continue()
 })
 await expectHTTPFailure(page,'PUT',`${path}/probes/${first.id}`,503,()=>review.getByRole('button',{name:'Apply or retry selected actions',exact:true}).click())
 await expect(review.getByRole('status')).toHaveCount(2)
 await review.getByRole('button',{name:'Close review',exact:true}).click()
 await expect(page.getByRole('heading',{name:'No matching probes',exact:true})).toBeVisible()
})
