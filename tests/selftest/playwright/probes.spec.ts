import { createServer } from 'node:http'
import { test, expect, expectHTTPFailure } from './fixtures'

async function bind(api: any, path: string, name: string, testId = 'SELF-CHECK', environmentId = 'local') {
 return api.call('POST', `${path}/probes`, { name, suiteId: 'health', testId, environmentId, endpoint: 'api' })
}

test('Probe overview separates observations and supports retained investigation', { tag: '@STUDIO-PROBE-OVERVIEW-001' }, async ({page,api},testInfo) => {
 const target=createServer((req,res)=>{res.statusCode=req.url==='/fail'?503:200;res.end('ready')})
 await new Promise<void>(resolve=>target.listen(0,'127.0.0.1',resolve))
 try {
  const address=target.address();if(!address||typeof address==='string')throw new Error('Target unavailable')
  const {project,path}=await api.scaffold();await api.createCheck(path)
  await bind(api,path,'Passing homepage')
  for(let i=0;i<30;i++)await api.run(path)
  await api.call('PUT',`${path}/environments/beta`,{id:'beta',name:'Beta target',applicationId:'app',stage:'local',endpoints:{api:`http://127.0.0.1:${address.port}`}},0)
  await api.call('POST',`${path}/suites/health/tests`,{id:'FAIL',title:'Failing entry',applicationId:'app',type:'https',runner:'http',state:'enabled',safety:'safe',rationale:'Reads a controlled fixture',category:'Availability',timeoutSeconds:1,dependencies:[],requiredBindings:[],tags:[],check:{endpoint:'api',path:'/fail',method:'GET',statusCodes:[200]}})
  const draft=await api.call('POST',`${path}/suites/health/catalog-drafts`,{});await api.call('POST',`${path}/suites/health/catalog-drafts/${draft.id}/publish`,{activate:true},draft.revision)
  await bind(api,path,'Failing entry','FAIL','beta')
  const created=await api.call('POST',`${path}/runs`,{suiteId:'health',environmentId:'beta',testIds:['FAIL'],timeoutSeconds:10})
  await expect.poll(async()=>(await api.call('GET',`${path}/runs/${created.id}`)).data.state).toBe('completed')
  await page.goto(`/projects/${project}/probes`)
  const passing=page.getByRole('article',{name:'Passing homepage',exact:true}), failing=page.getByRole('article',{name:'Failing entry',exact:true})
  await page.locator('#probe-app-filter').selectOption('app')
  await page.getByRole('button',{name:'Apply filters',exact:true}).click()
  await expect(passing).toContainText('passed');await expect(failing).toContainText('unexpected HTTP status 503')
  await expect(failing).toContainText('0/1');await expect(passing).toContainText('30/30')
  const checks=passing.getByRole('group',{name:'Recent logical checks'}).getByRole('link')
  await expect(checks).toHaveCount(30)
  await expect(checks.first()).toHaveAccessibleName(/^passed · /)
  await checks.first().focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  expect(await checks.first().evaluate(element=>getComputedStyle(element).outlineStyle)).toBe('solid')
  const passedColor=await checks.first().evaluate(element=>getComputedStyle(element).backgroundColor)
  expect(await failing.locator('.check').evaluate(element=>getComputedStyle(element).backgroundColor)).not.toBe(passedColor)
  await testInfo.attach('probe-overview-light',{body:await page.screenshot({fullPage:true}),contentType:'image/png'})
  const runURL=await checks.first().getAttribute('href')
  await checks.first().press('Enter')
  await expect(page).toHaveURL(new RegExp(runURL!.replace(/[?]/g,'\\?')+'$'))
  await page.goto(`/projects/${project}/probes`)
  await failing.getByRole('link',{name:'View history',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Test history',exact:true})).toBeVisible()
  await expect(page.locator('.history-run')).toHaveCount(1)
  expect(new URL(page.url()).searchParams.get('environment')).toBe('beta')
  await page.goto(`/projects/${project}/probes`);await page.setViewportSize({width:390,height:844});await page.getByLabel('Color theme').selectOption('dark')
  await expect(checks).toHaveCount(30)
  const pills=await checks.evaluateAll(elements=>elements.map(element=>{const rect=element.getBoundingClientRect();return {top:rect.top,width:rect.width,height:rect.height,text:element.textContent}}))
  expect(new Set(pills.map(pill=>pill.top)).size).toBe(1)
  expect(pills.every(pill=>pill.width<=8&&pill.width>=3&&pill.height===28&&!pill.text)).toBe(true)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await testInfo.attach('probe-overview-mobile',{body:await page.screenshot({fullPage:true}),contentType:'image/png'})
 }finally{target.closeAllConnections();await new Promise<void>(resolve=>target.close(()=>resolve()))}
})

