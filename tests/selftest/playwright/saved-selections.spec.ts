import { test, expect, expectHTTPFailure } from './fixtures'

test('saved filters and explicit selections freeze reviewed run inputs', { tag: '@STUDIO-SELECTIONS-001' }, async ({ page, api }) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path)
  const suite = `${path}/suites/health`
  const primary = await api.call('GET', `${suite}/tests/SELF-CHECK`)
  await api.call('POST', `${suite}/tests`, { ...primary.data, id: 'CHILD-CHECK', title: 'Child response', category: 'Service / Read', tags: ['smoke'], dependencies: ['SELF-CHECK'] })
  const draft = await api.call('POST', `${suite}/catalog-drafts`, {})
  const release = await api.call('POST', `${suite}/catalog-drafts/${draft.id}/publish`, { activate: true }, draft.revision)
  await page.goto(`/projects/${project}/catalog`)
  await page.getByRole('checkbox', { name: 'Select SELF-CHECK', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Select CHILD-CHECK', exact: true }).check()
  const saved = page.getByRole('region', { name: 'Saved selections', exact: true })
  await saved.getByRole('button', { name: 'Use selected tests', exact: true }).click()
  await saved.getByLabel('Saved selection name', { exact: true }).fill('Explicit smoke')
  await saved.getByLabel('Saved selection identifier', { exact: true }).fill('explicit-smoke')
  await saved.getByRole('button', { name: 'Save selection', exact: true }).click()
  await expect(saved.getByRole('status').filter({ hasText: 'Saved selection stored' })).toBeVisible()
  await saved.getByRole('button', { name: 'Preview saved selection', exact: true }).click()
  await expect(saved.getByRole('heading', { name: 'Resolved saved selection', exact: true })).toBeVisible()
  await saved.getByRole('button', { name: 'Archive saved selection', exact: true }).click()
  await expect(saved.getByRole('status').filter({ hasText: 'Saved selection archived' })).toBeVisible()
  await saved.getByRole('button', { name: 'Restore saved selection', exact: true }).click()
  await expect(saved.getByRole('status').filter({ hasText: 'Saved selection restored' })).toBeVisible()
  await saved.getByRole('button', { name: 'New saved selection', exact: true }).click()
  await saved.getByLabel('Saved selection name', { exact: true }).fill('Service smoke')
  await saved.getByLabel('Saved selection identifier', { exact: true }).fill('service-smoke')
  await saved.getByLabel('Selection definition', { exact: true }).selectOption('filter')
  await saved.getByLabel('Selection category', { exact: true }).fill('Service')
  await saved.getByRole('checkbox', { name: 'Include child categories', exact: true }).check()
  await saved.getByLabel('Required selection tags', { exact: true }).fill('smoke')
  await saved.getByRole('button', { name: 'Save selection', exact: true }).click()
  await expect(saved.getByRole('status').filter({ hasText: 'Saved selection stored' })).toBeVisible()
  const stored = await api.call('GET', `${suite}/saved-selections/service-smoke`)
  await api.call('PUT', `${suite}/saved-selections/service-smoke`, { ...stored.data, name: 'Reviewed smoke' }, stored.revision)
  await saved.getByLabel('Saved selection name', { exact: true }).fill('Unsaved concurrent name')
  await expectHTTPFailure(page, 'PUT', `${suite}/saved-selections/service-smoke`, 409, () => saved.getByRole('button', { name: 'Save selection', exact: true }).click())
  await expect(saved.getByRole('alert')).toContainText('Reload saved selection')
  await saved.getByRole('button', { name: 'Reload saved selection', exact: true }).click()
  await expect(saved.getByLabel('Saved selection name', { exact: true })).toHaveValue('Reviewed smoke')
  await saved.getByRole('button', { name: 'Preview saved selection', exact: true }).click()
  await expect(saved.getByText('1 requested tests · 2 tests including dependencies · revision 2', { exact: true })).toBeVisible()
  await saved.getByRole('link', { name: 'Open Test runs', exact: true }).click()
  await page.getByRole('button', { name: '+ New run', exact: true }).click()
  const form = page.getByRole('region', { name: 'Start a run', exact: true })
  await form.getByLabel('Suite', { exact: true }).selectOption('health')
  await form.getByText('Advanced selection and run options', { exact: true }).click()
  await expect(form.getByLabel('Saved selection', { exact: true }).getByRole('option', { name: 'Reviewed smoke', exact: true })).toBeAttached()
  await form.getByLabel('Target environment', { exact: true }).selectOption('local')
  await form.getByLabel('Saved selection', { exact: true }).selectOption('service-smoke')
  await form.getByRole('button', { name: 'Review run', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('preview any saved selection')
  await form.getByRole('button', { name: 'Preview saved selection', exact: true }).click()
  await expect(form.getByRole('status')).toContainText('Reviewed smoke · revision 2 · 2 tests including dependencies')
  await api.call('PUT', `${suite}/tests/SELF-CHECK`, { ...primary.data, title: 'Later published title' }, primary.revision)
  const newer = await api.call('POST', `${suite}/catalog-drafts`, {})
  await api.call('POST', `${suite}/catalog-drafts/${newer.id}/publish`, { activate: true }, newer.revision)
  await form.getByRole('button', { name: 'Review run', exact: true }).click()
  await form.getByRole('button', { name: 'Start run', exact: true }).click()
  const results = page.getByRole('region', { name: 'Final test results', exact: true })
  await expect(results.getByRole('cell', { name: 'passed', exact: true })).toHaveCount(2, { timeout: 20000 })
  const snapshot = page.getByRole('region', { name: 'Execution snapshot', exact: true })
  await expect(snapshot).toContainText('Reviewed smoke · revision 2')
  const runId = page.url().split('/').at(-1)
  const run = (await api.call('GET', `${path}/runs/${runId}`)).data
  expect(run.release.id).toBe(release.id)
  expect(run.request.testIds).toEqual(['CHILD-CHECK'])
  expect(run.tests.find((test: any) => test.id === 'SELF-CHECK').title).toBe('TestStudio health')
  const selection = await api.call('GET', `${suite}/saved-selections/service-smoke`)
  await api.call('PUT', `${suite}/saved-selections/service-smoke`, { ...selection.data, name: 'Future smoke' }, selection.revision)
  await page.reload()
  await expect(snapshot).toContainText('Reviewed smoke · revision 2')
  expect((await api.call('GET', `${path}/runs/${runId}`)).data.savedSelection).toEqual(run.savedSelection)
})
