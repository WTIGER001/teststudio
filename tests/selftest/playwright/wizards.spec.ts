import { test, expect, expectHTTPFailure, followNavigation } from './fixtures'

test('Guided setup and HTTPS creation preserve entries and recover without duplicate runs', { tag: '@STUDIO-WIZARD-001' }, async ({ page, api }, testInfo) => {
  const setup = page.locator('ts-project-setup')
  await setup.getByLabel('Project name', { exact: true }).fill('Wizard workspace')
  await expect(setup.getByLabel('Permanent identifier', { exact: true })).not.toBeVisible()
  await setup.getByText('Advanced details', { exact: true }).click()
  const project = await setup.getByLabel('Permanent identifier', { exact: true }).inputValue()
  expect(project).toMatch(/^wizard-workspace-[a-f0-9]{8}$/)
  const path = `/api/v1/projects/${project}`, suffix = project.slice(-8), appPath = `${path}/applications/customer-portal-${suffix}`
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await setup.getByLabel('Application name', { exact: true }).fill('Customer portal')
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await setup.getByLabel('Add a target environment now', { exact: true }).check()
  await setup.getByLabel('Base URL', { exact: true }).fill('http://127.0.0.1:8040')
  await setup.getByLabel('Stage', { exact: true }).selectOption('local')
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(setup.getByRole('heading', { name: 'Review your project setup', exact: true })).toBeFocused()
  expect((await api.call('GET', '/api/v1/projects')).items.some((row: any) => row.id === project)).toBe(false)
  await setup.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(setup.getByLabel('Base URL', { exact: true })).toHaveValue('http://127.0.0.1:8040')
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.route(`**${appPath}`, route => route.fulfill({ status: 403, json: { message: 'Application registration is temporarily denied.' } }))
  await expectHTTPFailure(page, 'PUT', appPath, 403, () => setup.getByRole('button', { name: 'Create project', exact: true }).click())
  await expect(setup.getByRole('alert')).toContainText('Project created. Retry continues')
  await page.unroute(`**${appPath}`)
  const environmentPath = `${path}/environments/development-${suffix}`
  await page.route(`**${environmentPath}`, async route => { await route.fetch(); await route.fulfill({ status: 503, json: { message: 'Target response interrupted after saving.' } }) })
  await expectHTTPFailure(page, 'PUT', environmentPath, 503, () => setup.getByRole('button', { name: 'Retry remaining setup', exact: true }).click())
  await expect(setup.getByRole('alert')).toContainText('Project, Application created.')
  await page.unroute(`**${environmentPath}`)
  await setup.getByRole('button', { name: 'Retry remaining setup', exact: true }).click()
  await expect(page).toHaveURL(`/projects/${project}/tests/new?suite=availability-${suffix}`)
  await page.getByRole('link', { name: 'HTTPS probe', exact: true }).click()
  const probe = page.locator('ts-https-wizard')
  await probe.getByLabel('Title', { exact: true }).fill('Service health')
  await probe.getByRole('button', { name: 'Continue', exact: true }).click()
  await probe.getByLabel('Use a registered environment', { exact: true }).check()
  await expect(probe.getByLabel('Target environment', { exact: true })).toHaveValue(`development-${suffix}`)
  await expect(probe.getByLabel('Expected response headers (JSON)', { exact: true })).not.toBeVisible()
  await probe.getByText('Advanced response assertions', { exact: true }).click()
  await probe.getByLabel('Expected response headers (JSON)', { exact: true }).fill('{bad json')
  await probe.getByText('Advanced response assertions', { exact: true }).click()
  await probe.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(probe.getByLabel('Expected response headers (JSON)', { exact: true })).toBeVisible()
  await expect(probe.getByLabel('Expected response headers (JSON)', { exact: true })).toBeFocused()
  await probe.getByLabel('Expected response headers (JSON)', { exact: true }).fill('')
  await probe.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(probe.getByLabel('Title', { exact: true })).toHaveValue('Service health')
  await probe.getByRole('button', { name: 'Continue', exact: true }).click()
  await probe.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(probe.getByLabel('Production-safety label', { exact: true })).toHaveValue('needs-review')
  await expect(probe.getByLabel('Safety rationale', { exact: true })).toHaveValue('Production safety has not been reviewed.')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme').selectOption('dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('https-review-mobile-dark', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  const keys: string[] = []
  await page.route(`**${path}/runs`, async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return }
    keys.push(route.request().headers()['idempotency-key'])
    await route.fetch()
    await route.fulfill({ status: 503, json: { message: 'The response was interrupted after run creation.' } })
  })
  await expectHTTPFailure(page, 'POST', `${path}/runs`, 503, () => probe.getByRole('button', { name: 'Save and run', exact: true }).click())
  await expect(probe.getByRole('alert')).toContainText('The test is saved.')
  await expect(probe.getByLabel('Safety rationale', { exact: true })).toBeDisabled()
  await page.unroute(`**${path}/runs`)
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === `${path}/runs`) keys.push(request.headers()['idempotency-key']) })
  await probe.getByRole('button', { name: 'Retry run', exact: true }).click()
  const results = page.getByRole('region', { name: 'Final test results', exact: true })
  await expect(results.getByRole('cell', { name: 'passed', exact: true })).toBeVisible({ timeout: 20000 })
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1])
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(1)
  const suitePath = `${path}/suites/availability-${suffix}`, suite = (await api.call('GET', `${path}/suites`)).items.find((row: any) => row.id === `availability-${suffix}`)
  expect(suite.data.activeReleaseId || '').toBe('')
  const run = (await api.call('GET', `${path}/runs/${page.url().split('/').at(-1)}`)).data
  await api.call('POST', `${suitePath}/releases/${run.release.id}/activate`, {}, suite.revision)
  await followNavigation(page, 'Test runs')
  await page.getByRole('button', { name: '+ New run', exact: true }).click()
  const form = page.getByRole('region', { name: 'Start a run', exact: true })
  await form.getByLabel('Suite', { exact: true }).selectOption(`availability-${suffix}`)
  await form.getByLabel('Target environment', { exact: true }).selectOption(`development-${suffix}`)
  await expect(form.getByLabel('Retries per test', { exact: true })).not.toBeVisible()
  await form.getByRole('button', { name: 'Review run', exact: true }).click()
  await expect(form).toContainText('Development · local')
  await form.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(form.getByLabel('Suite', { exact: true })).toHaveValue(`availability-${suffix}`)
  await form.getByRole('button', { name: 'Review run', exact: true }).click()
  await form.getByRole('button', { name: 'Start run', exact: true }).click()
  await expect(results.getByRole('cell', { name: 'passed', exact: true })).toBeVisible({ timeout: 20000 })
})
