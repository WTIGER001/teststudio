import { test, expect } from './fixtures'
import { startPublisher } from './cli-process'

test('publisher CLI confirms local and OIDC sessions through the browser', { tag: '@STUDIO-CLI-001' }, async ({ page, api }) => {
  await api.call('POST', '/api/v1/identity-providers', { id: 'cli-one', name: 'CLI identity one', issuer: 'http://127.0.0.1:8050/oidc/one', clientId: 'teststudio-public', disabled: false, autoProvision: true, scopes: ['openid', 'profile', 'email'], groupMappings: {}, membershipTtlSeconds: 0, reason: 'Verify CLI sign-in with a newly configured local OIDC fixture' })
  const local = await startPublisher('Local browser publisher')
  try {
    await page.goto(local.address)
    await expect(page.getByRole('heading', { name: 'Confirm CLI sign-in', exact: true })).toBeVisible()
    await expect(page.getByRole('definition').filter({ hasText: 'Local browser publisher' })).toBeVisible()
    await page.getByLabel('Terminal code', { exact: true }).fill(local.code)
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    const help = page.getByRole('dialog', { name: 'CLI sign-in help', exact: true })
    for (const name of ['Introduction', 'Concepts', 'Tutorials']) await expect(help.getByRole('heading', { name, exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByLabel('Terminal code', { exact: true })).toHaveValue(local.code)
    await page.getByLabel('Color theme').selectOption('dark')
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Approve CLI sign-in', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'CLI sign-in approved' })).toBeVisible()
    const session = await local.finished()
    const response = await page.request.get('/auth/session', { headers: { Cookie: `teststudio_session=${session.cookie}` } })
    const cli = await response.json()
    expect(cli.session.client).toBe('publisher-cli')
    expect(cli.session.clientName).toBe('Local browser publisher')
    expect(cli.session.authenticationMethod).toBe('local')
    const browser = await (await page.request.get('/auth/session')).json()
    expect(cli.user.id).toBe(browser.user.id)
    expect(cli.session.csrfToken).not.toBe(browser.session.csrfToken)
  } finally { await local.cleanup() }

  const root = await (await page.request.get('/auth/session')).json()
  const signedOut = await page.request.post('/auth/logout', { data: {}, headers: { Origin: 'http://127.0.0.1:8040', 'X-CSRF-Token': root.session.csrfToken } })
  expect(signedOut.ok()).toBe(true)
  const oidc = await startPublisher('OIDC browser publisher')
  try {
    await page.setViewportSize({ width: 1280, height: 900 })
    await page.goto(oidc.address)
    await page.getByRole('link', { name: 'Continue with CLI identity one', exact: true }).click()
    await page.getByLabel('Fixture subject', { exact: true }).fill('cli-publisher-subject')
    await page.getByLabel('Fixture email', { exact: true }).fill('cli-publisher@example.test')
    await page.getByRole('button', { name: 'Confirm fixture sign-in', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Confirm CLI sign-in', exact: true })).toBeVisible()
    expect(page.url()).toContain(new URL(oidc.address).pathname)
    await page.getByLabel('Terminal code', { exact: true }).fill(oidc.code)
    await page.getByRole('button', { name: 'Approve CLI sign-in', exact: true }).click()
    const session = await oidc.finished()
    const cli = await (await page.request.get('/auth/session', { headers: { Cookie: `teststudio_session=${session.cookie}` } })).json()
    const browser = await (await page.request.get('/auth/session')).json()
    expect(cli.session.provider).toBe('cli-one')
    expect(cli.session.authenticationMethod).toBe('oidc')
    expect(cli.session.providerRevision).toBe(browser.session.providerRevision)
    expect(cli.session.authenticationUntil).toBe(browser.session.authenticationUntil)
    expect(new Date(cli.session.expiresAt).getTime()).toBeLessThanOrEqual(new Date(browser.session.authenticationUntil).getTime())
    expect(cli.user.id).toBe(browser.user.id)
    expect(cli.session.csrfToken).not.toBe(browser.session.csrfToken)
    expect(JSON.stringify(session)).not.toMatch(/id_token|access_token|refresh_token|client_secret/)
  } finally { await oidc.cleanup() }

  expect((await (await page.request.get('/auth/session')).json()).session.authenticationMethod).toBe('oidc')
  const declined = await startPublisher('Declined publisher')
  try {
    await page.goto(declined.address)
    await page.getByRole('button', { name: 'Decline CLI sign-in', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'CLI sign-in declined' })).toBeVisible()
    await declined.declined()
  } finally { await declined.cleanup() }
})
