import { test, expect, expectHTTPFailure } from './fixtures'

test('Playwright editor retains drafts and freezes reviewed preparation input', { tag: '@STUDIO-EDITOR-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.call('PUT', `${path}/suites/browser`, { id: 'browser', name: 'Editor browser checks', applications: [], requiresTarget: false }, 0)
  const base = `${path}/suites/browser/playwright-drafts`
  await page.goto(`/projects/${project}/sources`)
  await page.getByLabel('Suite for sources', { exact: true }).selectOption('browser')
  await page.getByRole('button', { name: 'New Playwright draft', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Playwright editor', exact: true })
  await expect(editor.getByText('Unsaved changes', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Suite for sources', { exact: true })).toBeDisabled()
  const code = editor.getByRole('textbox', { name: 'Source code: checks/welcome.spec.ts', exact: true })
  await expect(code).toContainText('Welcome to TestStudio')
  await page.getByLabel('Draft name', { exact: true }).fill('Edited welcome checks')
  await code.click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText('\nexport const editorVersion = 1\n')
  const save = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().includes('/playwright-drafts/'))
  await editor.getByRole('button', { name: 'Save Playwright draft', exact: true }).click()
  const saved = await (await save).json()
  expect(saved.data.files[0].content).toContain('export const editorVersion = 1')
  await expect(editor.getByText('Saved revision 1', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Suite for sources', { exact: true })).toBeEnabled()
  await page.reload()
  await page.getByLabel('Suite for sources', { exact: true }).selectOption('browser')
  await page.getByRole('button', { name: 'Open draft Edited welcome checks', exact: true }).click()
  await expect(code).toContainText('export const editorVersion = 1')
  await page.getByLabel('File', { exact: true }).selectOption('catalog.json')
  await expect(editor.getByRole('textbox', { name: 'Source code: catalog.json', exact: true })).toContainText('@BROWSER-001')
  await page.getByLabel('File', { exact: true }).selectOption('checks/welcome.spec.ts')
  await editor.getByText('Add a source or helper file', { exact: true }).click()
  await editor.getByLabel('New file path', { exact: true }).fill('../escape.ts')
  await editor.getByRole('button', { name: 'Add file', exact: true }).click()
  await expect(editor.getByRole('alert')).toContainText('relative file path')
  await editor.getByLabel('New file path', { exact: true }).fill('checks/helper.ts')
  await editor.getByRole('button', { name: 'Add file', exact: true }).click()
  await expect(editor.getByRole('textbox', { name: 'Source code: checks/helper.ts', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'Remove selected file', exact: true }).click()
  await expect(editor.getByText('Saved revision 1', { exact: true })).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Validate and prepare draft', exact: true })).toBeEnabled()
  const queued = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/prepare'))
  await editor.getByRole('button', { name: 'Validate and prepare draft', exact: true }).click()
  const job = await (await queued).json()
  expect(job.data.sourceDraftId).toBe(saved.id)
  expect(job.data.sourceDraftRevision).toBe(1)
  expect(job.data.state).toBe('received')
  expect((await api.call('GET', `${path}/runs`)).items).toEqual([])
  await page.getByRole('button', { name: 'Cancel preparation', exact: true }).click()
  await page.getByLabel('Draft name', { exact: true }).fill('Unsaved local name')
  const remote = await api.call('PUT', `${base}/${saved.id}`, { ...saved.data, name: 'Concurrent server name' }, saved.revision)
  await expectHTTPFailure(page, 'PUT', `${base}/${saved.id}`, 409, () => editor.getByRole('button', { name: 'Save Playwright draft', exact: true }).click())
  await expect(editor.getByRole('alert')).toContainText('changed on the server')
  await expect(page.getByLabel('Draft name', { exact: true })).toHaveValue('Unsaved local name')
  expect((await api.call('GET', `${base}/${saved.id}`)).revision).toBe(remote.revision)
  page.once('dialog', dialog => dialog.dismiss())
  await page.locator('a.brand').click()
  await expect(page).toHaveURL(`/projects/${project}/sources`)
  await editor.getByRole('button', { name: 'Discard local changes', exact: true }).click()
  await editor.getByRole('button', { name: 'Open draft Edited welcome checks', exact: true }).click()
  await expect(page.getByLabel('Draft name', { exact: true })).toHaveValue('Concurrent server name')
  await page.getByLabel('Color theme').selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await code.focus()
  await page.keyboard.press('Tab')
  await expect(code).not.toBeFocused()
  await testInfo.attach('playwright-editor-mobile-dark', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Import and sync tests help', exact: true })).toContainText('Playwright editor')
})
