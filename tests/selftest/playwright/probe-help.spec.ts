import { test, expect } from './fixtures'

test('Probe visual examples preserve edits and locate current controls', { tag: '@STUDIO-PROBE-HELP-001' }, async ({ page, api }, testInfo) => {
  const { project } = await api.scaffold()
  await page.goto(`/projects/${project}/tests/new/https`)
  await page.getByLabel('Title', { exact: true }).fill('Unsaved example check')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Website URL', { exact: true }).fill('https://example.org/health')
  let mutations = 0
  page.on('request', r => { if (!['GET', 'HEAD'].includes(r.method())) mutations++ })
  for (const theme of ['light', 'dark']) {
    await page.getByLabel('Color theme').selectOption(theme)
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    const help = page.getByRole('dialog', { name: 'Create HTTPS probe help', exact: true })
    await help.getByRole('button', { name: 'Tutorials', exact: true }).click()
    await expect(help.locator('ts-probe-url-field input')).toHaveValue('https://example.com/')
    await expect(help.locator('ts-probe-url-field input')).toHaveAttribute('readonly', '')
    await expect(help.locator('ts-probe-review')).toContainText('GET https://example.com/')
    await help.getByRole('button', { name: 'Show me Website URL', exact: true }).click()
    await expect(help).not.toBeVisible()
    await expect(page.locator('#probe-url')).toBeFocused()
    await expect(page.locator('#probe-url')).toHaveValue('https://example.org/health')
    await page.getByRole('button', { name: 'Return to help', exact: true }).click()
    await expect(help).toBeVisible()
    await help.getByRole('button', { name: 'Show me Review', exact: true }).click()
    await expect(help.getByRole('status')).toContainText('not available on the current step')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Help', exact: true })).toBeFocused()
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Create HTTPS probe help', exact: true })
  await drawer.getByRole('button', { name: 'Tutorials', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await drawer.locator('.help-content').evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true)
  await testInfo.attach('probe-visual-help', { body: await page.screenshot(), contentType: 'image/png' })
  expect(mutations).toBe(0)
})
