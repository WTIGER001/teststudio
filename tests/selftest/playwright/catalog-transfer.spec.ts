import { readFile } from 'node:fs/promises'
import { test, expect, expectHTTPFailure } from './fixtures'

test('Page the authorized catalog and transfer native definitions with reviewed conflicts', { tag: '@STUDIO-TRANSFER-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path)
  const original = await api.run(path)
  const suite = `${path}/suites/health`
  const definition = (await api.call('GET', `${suite}/tests/SELF-CHECK`)).data
  for (let number = 1; number <= 34; number++) {
    const suffix = String(number).padStart(3, '0')
    await api.call('POST', `${suite}/tests`, { ...definition, id: `CHECK-${suffix}`, title: `Check ${suffix}`, category: 'Availability / Page', owner: 'QA', tags: ['smoke'] })
  }
  const listResponse = () => page.waitForResponse(response => response.url().includes(`${path}/tests?`) && response.request().method() === 'GET')
  const initial = listResponse()
  await page.goto(`/projects/${project}/catalog`)
  const firstPageResponse = await initial
  let firstPage = await firstPageResponse.json()
  await expect(page.getByRole('status').filter({ hasText: 'Showing 30 of 35 matching tests' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Select CHECK-001', exact: true }).check()
  await page.getByRole('button', { name: 'Load more tests', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Showing 35 of 35 matching tests' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Select SELF-CHECK', exact: true }).check()
  await page.getByLabel('Search tests', { exact: true }).fill('CHECK-034')
  await expect(page.getByRole('status').filter({ hasText: 'Showing 1 of 1 matching tests' })).toBeVisible()
  await expect(page.getByText('2 selected · 2 hidden by filters', { exact: true })).toBeVisible()
  const reloaded = listResponse()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  const resetResponse = await reloaded
  firstPage = await resetResponse.json()
  await expect(page.getByRole('checkbox', { name: 'Select CHECK-001', exact: true })).toBeChecked()
  const remote = await api.call('GET', `${suite}/tests/CHECK-034`)
  await api.call('PUT', `${suite}/tests/CHECK-034`, { ...remote.data, description: 'A concurrent edit after page one' }, remote.revision)
  const nextURL = new URL(resetResponse.url())
  nextURL.searchParams.set('cursor', firstPage.cursor)
  await expectHTTPFailure(page, 'GET', nextURL.href, 409, () => page.getByRole('button', { name: 'Load more tests', exact: true }).click())
  await expect(page.getByRole('alert')).toContainText('The catalog or your access changed between pages.')
  await page.getByRole('button', { name: 'Reload results', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Select CHECK-001', exact: true })).not.toBeChecked()
  const transfer = page.locator('details.catalog-transfer')
  await transfer.locator('summary').click()
  await transfer.getByLabel('Destination suite', { exact: true }).selectOption('health')
  await transfer.getByRole('button', { name: 'Export suite JSON', exact: true }).click()
  await expect(transfer.getByRole('link', { name: 'Download catalog JSON', exact: true })).toBeVisible()
  const exported = JSON.parse(await transfer.getByLabel('Catalog JSON document', { exact: true }).inputValue())
  expect(exported.tests).toHaveLength(35)
  expect(exported.originProjectId).toBe(project)
  const downloading = page.waitForEvent('download')
  await transfer.getByRole('link', { name: 'Download catalog JSON', exact: true }).click()
  const download = await downloading
  expect(download.suggestedFilename()).toBe('health.catalog.json')
  const file = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(file).toEqual(exported)
  const updated = { ...exported.tests.find((test: any) => test.id === 'SELF-CHECK'), title: 'Reviewed import title' }
  const added = { ...updated, id: 'IMPORTED', title: 'Imported native check', category: 'Transfer / Native' }
  const upload = async (document: unknown) => transfer.getByLabel('Load a JSON file', { exact: true }).setInputFiles({ name: 'new-catalog.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(document)) })
  await upload({ schemaVersion: 'teststudio.catalog/v1', tests: [{ ...updated, check: { ...updated.check, statusCodes: [999] } }] })
  await transfer.getByRole('button', { name: 'Validate import and preview', exact: true }).click()
  const plan = page.getByRole('region', { name: 'Review import changes', exact: true })
  await expect(plan.getByRole('list', { name: 'Catalog validation errors', exact: true })).toBeVisible()
  await expect(plan.getByRole('button', { name: 'Apply reviewed changes', exact: true })).toBeDisabled()
  expect((await api.call('GET', `${suite}/tests/SELF-CHECK`)).revision).toBe(1)
  await upload({ schemaVersion: 'teststudio.catalog/v1', tests: [updated, added] })
  const validated = page.waitForResponse(response => response.url().endsWith('/catalog-imports') && response.request().method() === 'POST')
  await transfer.getByRole('button', { name: 'Validate import and preview', exact: true }).click()
  const validPlan = await (await validated).json()
  await expect(plan.getByRole('heading', { name: 'Review import changes', exact: true })).toBeFocused()
  const current = await api.call('GET', `${suite}/tests/SELF-CHECK`)
  await api.call('PUT', `${suite}/tests/SELF-CHECK`, { ...current.data, title: 'Concurrent catalog title' }, current.revision)
  await expectHTTPFailure(page, 'POST', `${suite}/catalog-imports/${validPlan.id}/apply`, 409, () => plan.getByRole('button', { name: 'Apply reviewed changes', exact: true }).click())
  expect((await page.request.get(`${suite}/tests/IMPORTED`)).status()).toBe(404)
  await plan.getByRole('button', { name: 'Reload catalog', exact: true }).click()
  await expect(plan).toHaveCount(0)
  expect(JSON.parse(await transfer.getByLabel('Catalog JSON document', { exact: true }).inputValue()).tests[0].title).toBe('Reviewed import title')
  await transfer.getByRole('button', { name: 'Validate import and preview', exact: true }).click()
  await expect(plan.getByRole('table', { name: 'Proposed catalog changes', exact: true })).toContainText('Concurrent catalog title')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('reviewed-catalog-import-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await plan.getByRole('button', { name: 'Apply reviewed changes', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: /^Catalog changes applied/ })).toBeVisible()
  expect((await api.call('GET', `${suite}/tests/SELF-CHECK`)).data.title).toBe('Reviewed import title')
  expect((await api.call('GET', `${suite}/tests/IMPORTED`)).data.category).toBe('Transfer / Native')
  const beforePublish = await api.call('GET', `${suite}/release-registry`)
  expect(beforePublish.items).toHaveLength(1)
  expect(beforePublish.activeReleaseId).toBe(original.release.id)
  const retained = (await api.call('GET', `${path}/runs/${original.id}`)).data
  expect(retained.tests).toEqual(original.tests)
  await page.getByRole('button', { name: 'Validate and preview', exact: true }).click()
  const release = page.getByRole('region', { name: 'Release preview', exact: true })
  await expect(release.getByRole('article', { name: 'IMPORTED publication change', exact: true })).toContainText('added')
  await release.getByRole('button', { name: 'Publish release', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: /^Release published\. The active release stays unchanged/ })).toBeVisible()
  const published = await api.call('GET', `${suite}/release-registry`)
  expect(published.items).toHaveLength(2)
  expect(published.activeReleaseId).toBe(original.release.id)
})
