import { test, expect } from './fixtures'

test('Shared reliability history and external Angular components', { tag: '@STUDIO-RELIABILITY-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path); await api.run(path)
  const privatePath = `${path}/suites/health/tests/SELF-CHECK/reliability`
  const report = await api.call('GET', privatePath + '?environment=local&window=1m')
  expect(report.probes[0].metric).toBe('outcomes')
  expect(report.probes[0].totals.counts.passed).toBe(1)
  expect(report.probes[0].availability.percent).toBeNull()
  expect(report.probes[0].buckets.length).toBeGreaterThanOrEqual(30)
  await page.goto(`/projects/${project}/tests/health/SELF-CHECK/history?environment=local`)
  const history = page.getByRole('region', { name: 'Reliability history', exact: true })
  await expect(history.getByRole('article')).toContainText('pass rate')
  await history.getByLabel('Report period', { exact: true }).selectOption('7d')
  await expect(history.locator('.pill')).toHaveCount(29)
  await history.locator('.pill.passed').first().click()
  await expect(history.getByRole('button', { name: 'Inspect period' })).toBeVisible()
  await history.getByRole('button', { name: 'Inspect period' }).click()
  await expect(history.getByRole('button', { name: 'Return to full period' })).toBeVisible()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Test history help' })).toContainText('Reliability')
  await page.keyboard.press('Escape')
  await page.goto(`/projects/${project}/status-pages/new`)
  await page.getByLabel('Page title', { exact: true }).fill('Shared check history')
  await page.getByLabel('Default availability period', { exact: true }).selectOption('1m')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByText('Other test types', { exact: true }).click()
  await page.getByLabel('Test to include', { exact: true }).selectOption('health/SELF-CHECK')
  await page.getByLabel('Test environment', { exact: true }).selectOption('local')
  await page.getByRole('button', { name: 'Add selected test', exact: true }).click()
  await page.getByLabel('Public title 1', { exact: true }).fill('Public check')
  await page.getByLabel('Description 1 (optional)', { exact: true }).fill('Public outcomes')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Execution outcomes', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Edit status page', exact: true })).toBeVisible()
  const statusBase = `${path}/status-pages/${page.url().split('/').at(-1)}`
  const published = await api.call('POST', statusBase + '/publish', undefined, 1)
  const token = published.data.publicToken
  const visitor = await page.context().browser()!.newContext()
  const host = await visitor.newPage()
  const errors: string[] = []
  host.on('pageerror', error => errors.push(error.message))
  try {
    await host.goto('http://127.0.0.1:8050/angular-status/')
    await expect(host.getByRole('heading', { name: 'Release checks', exact: true })).toBeVisible()
    await host.getByLabel('Component', { exact: true }).selectOption('bar')
    await expect(host.locator('.pill')).toHaveCount(6)
    await host.getByLabel('Appearance', { exact: true }).selectOption('brand')
    expect(await host.locator('.pill.passed').evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(117, 68, 199)')
    await host.locator('.pill.timeout').focus(); await expect(host.locator('.pill.timeout')).toBeFocused()
    await host.keyboard.press('Enter')
    await expect(host.getByRole('button', { name: 'Inspect period' })).toBeVisible()
    for (const appearance of ['light', 'dark', 'brand']) {
      await host.getByLabel('Appearance', { exact: true }).selectOption(appearance)
      await host.setViewportSize({ width: 390, height: 844 })
      expect(await host.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach(`angular-status-bar-${appearance}`, { body: await host.screenshot({ fullPage: true }), contentType: 'image/png' })
    }
    await host.clock.install()
    await host.goto('http://127.0.0.1:8050/angular-status/?page=' + token)
    await expect(host.getByRole('heading', { name: 'Shared check history', exact: true })).toBeVisible()
    await expect(host.getByLabel('Report period', { exact: true })).toHaveValue('1m')
    await expect(host.getByRole('article')).toContainText('100.00%')
    const publicResponse = await visitor.request.get('http://127.0.0.1:8040/api/v1/public/status-pages/' + token)
    expect(publicResponse.headers()['access-control-allow-origin']).toBe('*')
    const publicText = await publicResponse.text()
    for (const value of [project, 'SELF-CHECK', 'environmentId', 'runId', 'http://127.0.0.1']) expect(publicText).not.toContain(value)
    const reads: string[] = []
    host.on('request', request => { if (request.url().includes('/api/v1/public/status-pages/')) reads.push(request.url()) })
    await host.getByRole('button', { name: 'Remove components' }).click()
    await expect(host.locator('teststudio-status-page')).toHaveCount(0)
    reads.length = 0
    await host.clock.fastForward(61000)
    expect(reads).toHaveLength(0)
    await host.getByRole('button', { name: 'Show components' }).click()
    await expect(host.getByRole('heading', { name: 'Shared check history', exact: true })).toBeVisible()
    await api.call('POST', statusBase + '/unpublish', undefined, 2)
    await host.clock.fastForward(16000)
    await expect(host.getByRole('alert')).toContainText('no longer published')
    await expect(host.getByRole('heading', { name: 'Shared check history', exact: true })).toHaveCount(0)
    expect(errors).toEqual([])
  } finally { await visitor.close() }
})
