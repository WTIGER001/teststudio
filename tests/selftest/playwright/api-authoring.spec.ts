import { test, expect } from './fixtures'

test('Create an API draft with reviewed request policy and preserved wizard entries', { tag: '@STUDIO-API-AUTHOR-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold('api-auth-authoring')
  await page.goto(`/projects/${project}/configuration?kind=environments`)
  const registration = page.locator('ts-resource-registration-form')
  await registration.getByLabel('Name', { exact: true }).fill('Authenticated local target')
  await registration.getByText('Advanced details', { exact: true }).click()
  await registration.getByLabel('Permanent identifier', { exact: true }).fill('credential-target')
  await registration.getByRole('button', { name: 'Continue', exact: true }).click()
  await registration.getByLabel('Application', { exact: true }).selectOption('app')
  await registration.getByLabel('Stage', { exact: true }).selectOption('local')
  await registration.getByLabel('Base URL', { exact: true }).fill('https://unapproved.test')
  await registration.getByText('Advanced credentials', { exact: true }).click()
  await registration.getByRole('button', { name: 'Add credential binding', exact: true }).click()
  await registration.getByLabel('Approved credential reference 1', { exact: true }).selectOption('local-api-reader')
  await registration.getByText('Advanced credentials', { exact: true }).click()
  await registration.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(registration.getByLabel('Approved credential reference 1', { exact: true })).toBeFocused()
  await registration.getByLabel('Base URL', { exact: true }).fill('http://127.0.0.1:8040')
  await registration.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(registration).toContainText('api-login → local-api-reader')
  await registration.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(registration.getByLabel('Approved credential reference 1', { exact: true })).toHaveValue('local-api-reader')
  await registration.getByRole('button', { name: 'Continue', exact: true }).click()
  await registration.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Authenticated local target was created.' })).toBeVisible()
  expect((await api.call('GET', `${path}/environments`)).items.find((row: any) => row.id === 'credential-target').data.credentialBindings).toEqual({ 'api-login': 'local-api-reader' })
  await page.goto(`/projects/${project}/tests/new`)
  await page.getByRole('link', { name: 'API test', exact: true }).click()
  await expect(page).toHaveURL(`/projects/${project}/tests/new/api`)
  await page.getByLabel('Suite for this test', { exact: true }).selectOption('health')
  const editor = page.getByRole('region', { name: 'API test editor', exact: true })
  await expect(page.getByRole('region', { name: 'Record a browser test', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Source ZIP', { exact: true })).toHaveCount(0)
  await editor.getByRole('button', { name: 'New API draft', exact: true }).click()
  await editor.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(editor.getByLabel('API test title', { exact: true })).toBeFocused()
  await editor.getByLabel('API test title', { exact: true }).fill('Search inventory safely')
  await editor.getByText('Advanced details', { exact: true }).click()
  await editor.getByLabel('Permanent API test identifier', { exact: true }).fill('API-AUTHOR-001')
  await editor.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(editor.getByRole('heading', { name: 'Configure its first request', exact: true })).toBeFocused()
  await editor.getByLabel('Request path', { exact: true }).fill('/v1/../private')
  await editor.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(editor.getByLabel('Request path', { exact: true })).toBeFocused()
  await editor.getByLabel('Request path', { exact: true }).fill('/v1/search?limit=2')
  await editor.getByLabel('Request method', { exact: true }).selectOption('POST')
  await editor.getByLabel('Authentication', { exact: true }).selectOption('bearer')
  await expect(editor.getByLabel('Environment credential binding', { exact: true })).toHaveValue('api-login')
  await editor.getByLabel('JSON request data (optional)', { exact: true }).fill('{"query":"owned fixture"}')
  await editor.getByLabel('Requests are reviewed as read-only', { exact: true }).check()
  await editor.getByText('Advanced request policy', { exact: true }).click()
  await editor.getByLabel('Allowed path prefix', { exact: true }).fill('/private')
  await editor.getByText('Advanced request policy', { exact: true }).click()
  await editor.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(editor.getByLabel('Allowed path prefix', { exact: true })).toBeVisible()
  await expect(editor.getByLabel('Allowed path prefix', { exact: true })).toBeFocused()
  await editor.getByLabel('Allowed path prefix', { exact: true }).fill('/v1')
  await editor.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(editor.getByRole('heading', { name: 'Review the API source draft', exact: true })).toBeFocused()
  await expect(editor).toContainText('Needs review. Inspect the generated code and catalog before publication.')
  await expect(editor).toContainText('Reviewed read-only requests')
  await expect(editor).toContainText('bearer with environment binding api-login')
  await expect(editor).toContainText('"query":"owned fixture"')
  await editor.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(editor.getByLabel('Request path', { exact: true })).toHaveValue('/v1/search?limit=2')
  await expect(editor.getByLabel('JSON request data (optional)', { exact: true })).toHaveValue('{"query":"owned fixture"}')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Create test help', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await editor.getByRole('button', { name: 'Continue', exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('link', { name: 'Back to catalog', exact: true }).click()
  await expect(page).toHaveURL(`/projects/${project}/tests/new/api`)
  await editor.getByRole('button', { name: 'Create source draft', exact: true }).click()
  await expect(editor.getByRole('heading', { name: 'API test editor', exact: true })).toBeFocused()
  const source = editor.getByRole('textbox', { name: 'Source code: checks/api.spec.ts', exact: true })
  await expect(source).toContainText('@API-AUTHOR-001')
  await expect(source).toContainText('request.fetch')
  await expect(source).toContainText('/v1/search?limit=2')
  await editor.getByRole('button', { name: 'Save API draft', exact: true }).click()
  await expect(editor.getByRole('status').filter({ hasText: 'Draft saved at revision 1' })).toBeVisible()
  await editor.getByLabel('File', { exact: true }).selectOption('teststudio-suite.json')
  const manifest = editor.getByRole('textbox', { name: 'Source code: teststudio-suite.json', exact: true })
  await expect(manifest).toContainText('"type": "api"')
  await expect(manifest).toContainText('"pathPrefix": "/v1"')
  await expect(manifest).toContainText('"readOnly": true')
  await expect(manifest).toContainText('"scheme": "bearer"')
  await expect(manifest).toContainText('"binding": "api-login"')
  await editor.getByLabel('File', { exact: true }).selectOption('catalog.json')
  await expect(editor.getByRole('textbox', { name: 'Source code: catalog.json', exact: true })).toContainText('"safety": "needs-review"')
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(0)
  const drafts = await api.call('GET', `${path}/suites/health/playwright-drafts`)
  expect(drafts.items).toHaveLength(1)
  await page.getByLabel('Color theme', { exact: true }).selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(editor.getByRole('button', { name: 'Save API draft', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await testInfo.attach('api-source-mobile', { body: await page.screenshot(), contentType: 'image/png' })
})
