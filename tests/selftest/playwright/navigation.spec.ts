import { test, expect, followNavigation } from './fixtures'

test('sidebar groups testing and administration with keyboard and mobile navigation', { tag: '@STUDIO-NAV-001' }, async ({ page, api }, testInfo) => {
  const { project } = await api.scaffold()
  await page.goto(`/projects/${project}/catalog`)
  const navigation = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  const projectSection = navigation.locator('details[aria-label="Project administration"]')
  const automationSection = navigation.locator('details[aria-label="Automation"]')
  const advancedSection = navigation.locator('details[aria-label="Advanced testing"]')
  const installationSection = navigation.locator('details[aria-label="Installation administration"]')
  await expect(navigation.getByRole('heading', { name: 'Testing', exact: true })).toBeVisible()
  await expect(navigation.getByRole('link', { name: 'Test runs', exact: true })).toBeVisible()
  await expect(automationSection).not.toHaveAttribute('open', '')
  await expect(advancedSection).not.toHaveAttribute('open', '')
  await expect(navigation.getByRole('link', { name: 'Import and sync tests', exact: true, includeHidden: true })).toBeHidden()
  await expect(projectSection).not.toHaveAttribute('open', '')
  await expect(installationSection).not.toHaveAttribute('open', '')
  await expect(navigation.getByRole('link', { name: 'Users', exact: true, includeHidden: true })).toBeHidden()
  await followNavigation(page, 'Suites')
  await expect(page.getByRole('heading', { name: 'Suites', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '+ New suite', exact: true }).click()
  const wizard = page.locator('ts-resource-registration-form')
  await wizard.getByLabel('Name', { exact: true }).fill('Browser journeys')
  await expect(wizard.getByLabel('Permanent identifier', { exact: true })).not.toBeVisible()
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await wizard.getByLabel('Application (optional)', { exact: true }).selectOption('app')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(wizard).toContainText('TestStudio')
  await wizard.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(wizard.getByLabel('Application (optional)', { exact: true })).toHaveValue('app')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await wizard.getByRole('button', { name: 'Create', exact: true }).click()
  const suite = page.getByRole('article', { name: 'Browser journeys', exact: true })
  await suite.getByRole('link', { name: 'Create test in Browser journeys', exact: true }).click()
  await page.getByRole('link', { name: 'HTTPS probe', exact: true }).click()
  await expect(navigation.getByRole('link', { name: 'Test catalog', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByLabel('Suite', { exact: true }).getByRole('option', { selected: true })).toHaveText('Browser journeys')
  await followNavigation(page, 'Suites')
  await page.getByRole('button', { name: 'Suite settings for Browser journeys', exact: true }).click()
  await page.getByLabel('Suite description', { exact: true }).fill('Unsaved suite settings')
  page.once('dialog', dialog => dialog.dismiss())
  await followNavigation(page, 'Test catalog')
  await expect(page).toHaveURL(`/projects/${project}/suites`)
  page.once('dialog', dialog => dialog.accept())
  await followNavigation(page, 'Test catalog')
  await followNavigation(page, 'Import and sync tests')
  await expect(page.getByRole('heading', { name: 'Import and sync tests', exact: true })).toBeVisible()
  await expect(advancedSection).toHaveAttribute('open', '')
  await followNavigation(page, 'Test catalog')
  await expect(advancedSection).not.toHaveAttribute('open', '')
  await testInfo.attach('grouped-sidebar', { body: await page.screenshot(), contentType: 'image/png' })
  await projectSection.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(projectSection).toHaveAttribute('open', '')
  await navigation.getByRole('link', { name: 'Project settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Project settings', exact: true })).toBeVisible()
  await expect(projectSection).toHaveAttribute('open', '')
  await page.goto('/settings/users')
  await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible()
  await expect(installationSection).toHaveAttribute('open', '')
  await expect(navigation.getByRole('link', { name: 'Users', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByLabel('Project', { exact: true }).selectOption(project)
  await expect(projectSection).not.toHaveAttribute('open', '')
  await expect(installationSection).not.toHaveAttribute('open', '')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme').selectOption('dark')
  const menu = page.getByRole('button', { name: 'Navigation', exact: true })
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('navigation', { name: 'Main navigation', includeHidden: true })).toBeHidden()
  await menu.click()
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await expect(navigation.getByRole('link', { name: 'Your account', exact: true })).toBeVisible()
  await projectSection.locator('summary').click()
  await navigation.getByRole('link', { name: 'Project settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Project settings', exact: true })).toBeVisible()
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await menu.click()
  await expect(projectSection).toHaveAttribute('open', '')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('grouped-sidebar-mobile', { body: await page.screenshot(), contentType: 'image/png' })
  await page.getByLabel('Color theme').selectOption('light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await navigation.getByRole('link', { name: 'Test catalog', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Test catalog', exact: true })).toBeVisible()
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
})
