import { test, expect } from './fixtures'

test('Browse category paths, combine filters, retain selection, and manage lifecycle', { tag: '@STUDIO-BROWSE-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.call('PUT', `${path}/applications/service`, { id: 'service', name: 'Example service', description: '' }, 0)
  await api.call('PUT', `${path}/suites/other`, { id: 'other', name: 'Other suite', applications: ['app', 'service'], requiresTarget: true }, 0)
  const create = async (id: string, title: string, category: string, suite = 'health', extra = {}) => api.call('POST', `${path}/suites/${suite}/tests`, {
    id, title, description: 'New category browsing fixture', applicationId: 'app', category, tags: ['smoke'], owner: 'QA', type: 'https', runner: 'http', state: 'enabled', safety: 'safe', rationale: 'Read-only local fixture', dependencies: [], requiredBindings: [], timeoutSeconds: 10, source: 'new-local-probes', check: { endpoint: 'api', path: '/healthz', method: 'GET', statusCodes: [200] }, ...extra
  })
  await create('ROOT', 'A Root check', 'Availability')
  await create('LOCAL', 'B Local check', 'Availability / Local')
  await create('CHILD', 'C Nested check', 'Availability/Local/Checkout', 'health', { tags: ['regression'] })
  await create('LOCAL', 'Z Other suite check', 'Availability/Local', 'other')
  await create('OTHER', 'D Separate category', 'AvailabilityExtra', 'other', { applicationId: 'service', owner: 'Service team', source: 'new-service-probes' })
  await page.goto(`/projects/${project}/catalog`)
  const table = page.getByRole('table', { name: 'Tests in this project', exact: true })
  const row = (id: string) => table.getByRole('row').filter({ has: page.getByRole('checkbox', { name: `Select ${id}`, exact: true }) })
  await expect(table.getByRole('row')).toHaveCount(6)
  await page.getByRole('checkbox', { name: 'Select ROOT', exact: true }).check()
  await page.getByRole('radio', { name: 'By category', exact: true }).check()
  const categories = page.getByRole('navigation', { name: 'Catalog categories', exact: true })
  await categories.getByRole('button', { name: 'View all in Availability', exact: true }).click()
  await expect(table.getByRole('row')).toHaveCount(5)
  await expect(row('OTHER')).toHaveCount(0)
  await categories.getByRole('button', { name: 'View all in Local', exact: true }).click()
  await expect(table.getByRole('row')).toHaveCount(4)
  await expect(page.getByText('1 selected · 1 hidden by filters', { exact: true })).toBeVisible()
  const advanced = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Advanced filters$/ }) })
  await advanced.locator('summary').click()
  await page.getByLabel('Include child categories', { exact: true }).uncheck()
  await expect(table.getByRole('row')).toHaveCount(3)
  await page.getByLabel('Filter by suite', { exact: true }).selectOption('health')
  await expect(table.getByRole('row')).toHaveCount(2)
  await page.getByLabel('Filter by application', { exact: true }).selectOption({ label: 'Example service' })
  await expect(page.getByRole('heading', { name: 'No matching tests.', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(table.getByRole('row')).toHaveCount(6)
  await expect(page.getByRole('checkbox', { name: 'Select ROOT', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: 'Table', exact: true }).check()
  await expect(categories).toHaveCount(0)
  await page.getByLabel('Sort tests', { exact: true }).selectOption('title-desc')
  await expect(table.getByRole('row').nth(1)).toContainText('Z Other suite check')
  await page.getByLabel('Search tests', { exact: true }).fill('root')
  await page.getByLabel('Tag', { exact: true }).selectOption('smoke')
  await page.getByLabel('Owner', { exact: true }).selectOption('QA')
  await page.getByLabel('Runner', { exact: true }).selectOption('http')
  await page.getByLabel('Safety label', { exact: true }).selectOption('safe')
  await page.getByLabel('Source', { exact: true }).selectOption('new-local-probes')
  await expect(table.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByLabel('Sort tests', { exact: true }).selectOption('title')
  await row('ROOT').locator('summary').click()
  await row('ROOT').getByRole('button', { name: 'Duplicate', exact: true }).click()
  await page.getByLabel('New permanent identifier', { exact: true }).fill('COPY')
  await page.getByRole('button', { name: 'Create duplicate', exact: true }).click()
  await expect(row('COPY')).toContainText('draft')
  await row('COPY').getByRole('button', { name: 'Enable', exact: true }).click()
  await expect(row('COPY')).toContainText('enabled')
  await row('COPY').getByRole('button', { name: 'Disable', exact: true }).click()
  await expect(row('COPY')).toContainText('disabled')
  await row('COPY').locator('summary').click()
  await row('COPY').getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(row('COPY')).toHaveCount(0)
  await page.getByLabel('Lifecycle state', { exact: true }).selectOption('archived')
  await row('COPY').getByRole('button', { name: 'Restore', exact: true }).click()
  await expect(table).toHaveCount(0)
  await page.getByLabel('Lifecycle state', { exact: true }).selectOption('active')
  await expect(row('COPY')).toContainText('enabled')
  await row('COPY').locator('summary').click()
  await row('COPY').getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revision history · COPY', exact: true })).toBeFocused()
  await expect(page.getByText(/^Revision 5 ·/)).toBeVisible()
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  await page.getByRole('radio', { name: 'By category', exact: true }).check()
  await page.getByLabel('Color theme', { exact: true }).selectOption('dark')
  await categories.getByRole('button', { name: 'View all in Availability', exact: true }).click()
  await expect(categories.getByRole('button', { name: 'View all in Availability', exact: true })).toHaveAttribute('aria-current', 'true')
  expect((await row('ROOT').locator('.test-identity').boundingBox())!.width).toBeGreaterThanOrEqual(180)
  await testInfo.attach('catalog-categories-dark', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme', { exact: true }).selectOption('light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const local = categories.locator('summary').filter({ hasText: /^Local/ })
  await local.focus()
  await page.keyboard.press('Enter')
  await expect(local.locator('..')).not.toHaveAttribute('open', '')
  await testInfo.attach('catalog-categories-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
