import { test, expect, expectHTTPFailure } from './fixtures'

test('Save current definitions directly, preserve history and pins, and reject stale edits', { tag: '@STUDIO-PUBLISH-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path)
  const original = await api.run(path)
  const suite = `${path}/suites/health`
  await api.call('POST', `${path}/schedules`, { id: 'pinned', name: 'Keep original version', enabled: false, kind: 'interval', intervalSeconds: 3600, timezone: 'UTC', overlap: 'skip', request: { suiteId: 'health', environmentId: 'local', releaseId: original.release.id, timeoutSeconds: 60 } })
  await page.goto(`/projects/${project}/catalog`)
  const row = page.getByRole('row').filter({ hasText: 'SELF-CHECK' })
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Edit test', exact: true })
  await editor.getByLabel('Title', { exact: true }).fill('Saved health check')
  const current = await api.call('GET', `${suite}/tests/SELF-CHECK`)
  await api.call('PUT', `${suite}/tests/SELF-CHECK`, { ...current.data, title: 'Concurrent health check' }, current.revision)
  await expectHTTPFailure(page, 'POST', `${suite}/tests/SELF-CHECK/save`, 409, () => editor.getByRole('button', { name: 'Save changes', exact: true }).click())
  await expect(editor.getByLabel('Title', { exact: true })).toHaveValue('Saved health check')
  expect((await api.call('GET', `${suite}/release-registry`)).activeReleaseId).toBe(original.release.id)
  await editor.getByRole('button', { name: 'Close editor', exact: true }).click()
  await page.reload()
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await editor.getByLabel('Title', { exact: true }).fill('Saved health check')
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(editor).toHaveCount(0)
  await expect(row).toContainText('Saved health check')
  await expect(page.getByRole('button', { name: /Publish|Validate and preview|Save and activate/ })).toHaveCount(0)
  const registry = await api.call('GET', `${suite}/release-registry`)
  expect(registry.items).toHaveLength(2)
  expect(registry.activeReleaseId).not.toBe(original.release.id)
  const saved = await api.call('GET', `${suite}/tests/SELF-CHECK`)
  expect(saved.savedVersionId).toBe(registry.activeReleaseId)
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(1)
  const retained = (await api.call('GET', `${path}/runs/${original.id}`)).data
  expect(retained.release.id).toBe(original.release.id)
  expect(retained.tests[0].title).toBe('TestStudio health')
  expect((await api.call('GET', `${path}/schedules/pinned`)).data.request.releaseId).toBe(original.release.id)
  const following = await api.run(path)
  expect(following.release.id).toBe(registry.activeReleaseId)
  expect(following.tests[0].title).toBe('Saved health check')
  await page.getByLabel('Color theme').selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('direct-save-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
