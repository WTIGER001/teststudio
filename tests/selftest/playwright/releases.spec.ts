import { test, expect, expectHTTPFailure } from './fixtures'

test('retained releases compare and roll back without changing run snapshots or pins', { tag: '@STUDIO-RELEASES-001' }, async ({ page, api }) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path)
  const first = (await api.call('GET', `${path}/suites/health/release-registry`)).items[0]
  const firstRun = await api.run(path)
  const definition = await api.call('GET', `${path}/suites/health/tests/SELF-CHECK`)
  await api.call('PUT', `${path}/suites/health/tests/SELF-CHECK`, { ...definition.data, title: 'New release health title' }, definition.revision)
  const draft = await api.call('POST', `${path}/suites/health/catalog-drafts`, {})
  const second = await api.call('POST', `${path}/suites/health/catalog-drafts/${draft.id}/publish`, { activate: true }, draft.revision)
  const secondRun = await api.run(path)
  await api.call('POST', `${path}/schedules`, { id: 'release-pin', name: 'Pinned retained release', enabled: false, kind: 'interval', intervalSeconds: 60, timezone: 'UTC', overlap: 'skip', request: { suiteId: 'health', environmentId: 'local', releaseId: second.id, executionLocation: 'local', timeoutSeconds: 60 } })
  const route = `/projects/${project}/releases?suiteId=health&releaseId=${first.id}`
  await page.goto(route)
  await expect(page.getByRole('heading', { name: 'Suite releases', exact: true })).toBeVisible()
  const comparison = page.getByRole('table', { name: 'Release definition changes', exact: true })
  await expect(comparison.getByRole('row').filter({ hasText: 'SELF-CHECK' })).toContainText('Changed')
  await expect(comparison.getByRole('row').filter({ hasText: 'SELF-CHECK' })).toContainText('title')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Suite releases help', exact: true })
  for (const name of ['Introduction', 'Concepts', 'Tutorials']) await expect(help.getByRole('heading', { name, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  const registry = await api.call('GET', `${path}/suites/health/release-registry`)
  await api.call('POST', `${path}/suites/health/releases/${first.id}/activate`, {}, registry.suiteRevision)
  await expectHTTPFailure(page, 'POST', `${path}/suites/health/releases/${first.id}/activate`, 409, () => page.getByRole('button', { name: 'Activate selected release', exact: true }).click())
  await expect(page.getByRole('alert')).toContainText('Refresh retained releases')
  await expect(page.getByRole('button', { name: 'Activate selected release', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Refresh retained releases', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Activate selected release', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: `Inspect release ${second.id}`, exact: true }).click()
  await page.getByRole('button', { name: 'Activate selected release', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Release activated for future runs' })).toBeVisible()
  await page.getByRole('button', { name: `Inspect release ${first.id}`, exact: true }).click()
  await page.getByRole('button', { name: 'Activate selected release', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Release activated for future runs' })).toBeVisible()
  const active = await api.call('GET', `${path}/suites/health/release-registry`)
  expect(active.activeReleaseId).toBe(first.id)
  const retainedFirst = (await api.call('GET', `${path}/runs/${firstRun.id}`)).data
  const retainedSecond = (await api.call('GET', `${path}/runs/${secondRun.id}`)).data
  expect(retainedFirst.release.id).toBe(first.id)
  expect(retainedSecond.release.id).toBe(second.id)
  expect(retainedFirst.tests[0].title).toBe('TestStudio health')
  expect(retainedSecond.tests[0].title).toBe('New release health title')
  expect((await api.call('GET', `${path}/schedules/release-pin`)).data.request.releaseId).toBe(second.id)
  const following = await api.run(path)
  expect(following.release.id).toBe(first.id)
  const pinned = await api.call('POST', `${path}/runs`, { suiteId: 'health', environmentId: 'local', releaseId: second.id, timeoutSeconds: 60 })
  expect((await api.call('GET', `${path}/runs/${pinned.id}`)).data.release.id).toBe(second.id)
  await expect.poll(async () => (await api.call('GET', `${path}/runs/${pinned.id}`)).data.state).toBe('completed')
  await page.getByLabel('Color theme').selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const suite = (await api.call('GET', `${path}/suites`)).items.find((item: any) => item.id === 'health')
  await api.call('PUT', `${path}/suites/health`, { ...suite.data, archived: true }, suite.revision)
  await page.getByRole('button', { name: 'Refresh retained releases', exact: true }).click()
  await expect(page.getByText('This suite is archived. Its releases remain readable. Restore the suite before activation.', { exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Retained suite releases', exact: true }).getByRole('button', { name: /Inspect release/ })).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Activate selected release', exact: true })).toHaveCount(0)
})
