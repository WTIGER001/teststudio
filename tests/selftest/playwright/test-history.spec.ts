import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { test, expect, expectHTTPFailure } from './fixtures'

test('Retain test identity, saved run snapshots and evidence through archive and working removal', { tag: '@STUDIO-HISTORY-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path)
  const first = await api.run(path), base = `${path}/suites/health/tests/SELF-CHECK`
  const generated = await promisify(execFile)(process.execPath, ['/suite/diagnostic-media.mjs', `/tmp/teststudio-diagnostics-${project}`, 'website'], { timeout: 15000, maxBuffer: 4096 })
  expect(JSON.parse(generated.stdout).closed).toBe(true)
  const prepared = await page.request.post('http://127.0.0.1:8050/history/prepare', { data: { project, run: first.id } })
  expect(prepared.ok(), await prepared.text()).toBe(true)
  const retention = await api.call('GET', `${path}/runs/${first.id}/retention`)
  await api.call('PUT', `${path}/runs/${first.id}/retention/pin`, { pinned: true, reason: 'Retain lifecycle investigation' }, retention.revision)
  const current = await api.call('GET', base)
  await api.call('PUT', base, { ...current.data, title: 'Updated health definition' }, current.revision)
  const draft = await api.call('POST', `${path}/suites/health/catalog-drafts`, {})
  await api.call('POST', `${path}/suites/health/catalog-drafts/${draft.id}/publish`, { activate: true }, draft.revision)
  const second = await api.run(path)
  const latest = await api.call('GET', base)
  await api.call('POST', `${base}/actions/archive`, {}, latest.revision)
  const suite = await api.call('GET', `${path}/suites/health/lifecycle`)
  await api.call('POST', `${path}/suites/health/actions/archive`, {}, suite.revision)

  await page.goto(`/projects/${project}/releases?suiteId=health`)
  await page.getByRole('button', { name: `Inspect release ${first.release.id}`, exact: true }).click()
  await page.getByText('Published test definitions', { exact: true }).click()
  await page.getByRole('link', { name: 'TestStudio health', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Test history', exact: true })).toBeVisible()
  await expect(page.getByText('This suite is archived.', { exact: false })).toBeVisible()
  const firstRow = page.getByRole('article', { name: `Run ${first.id}`, exact: true })
  const secondRow = page.getByRole('article', { name: `Run ${second.id}`, exact: true })
  await expect(firstRow.getByRole('heading', { name: 'TestStudio health', exact: true })).toBeVisible()
  await expect(secondRow.getByRole('heading', { name: 'Updated health definition', exact: true })).toBeVisible()
  await firstRow.getByRole('link', { name: 'Inspect run and evidence', exact: true }).click()
  const screenshot = page.getByRole('article', { name: 'retained-screenshot.png', exact: true })
  await screenshot.getByRole('button', { name: 'View', exact: true }).click()
  await expect(page.getByAltText('retained-screenshot.png', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close preview', exact: true }).click()
  await expect(screenshot.getByRole('button', { name: 'View', exact: true })).toBeFocused()
  await page.getByRole('link', { name: 'TestStudio health', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Return to run', exact: true })).toBeVisible()

  const removed = await page.request.post('http://127.0.0.1:8050/history/remove-working', { data: { project, run: first.id } })
  expect(removed.ok(), await removed.text()).toBe(true)
  await page.getByRole('button', { name: 'Refresh history', exact: true }).click()
  await expect(page.getByText('The working definition is removed.', { exact: false })).toBeVisible()
  await expect(firstRow).toBeVisible()
  await expect(secondRow).toBeVisible()
  await page.getByText('Advanced revision history', { exact: true }).click()
  await expect(page.locator('summary').filter({ hasText: /^Revision 1 ·/ })).toBeVisible()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Test history help', exact: true })
  for (const name of ['Introduction', 'Concepts', 'Tutorials']) await expect(help.getByRole('heading', { name, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Help', exact: true })).toBeFocused()
  for (const theme of ['light', 'dark']) {
    await page.getByLabel('Color theme').selectOption(theme)
    await page.setViewportSize(theme === 'light' ? { width: 1280, height: 900 } : { width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await testInfo.attach(`retained-history-${theme}`, { body: await page.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
  }
  await page.setViewportSize({ width: 1280, height: 900 })
  await firstRow.getByRole('link', { name: 'Inspect run and evidence', exact: true }).click()
  const trace = page.getByRole('article', { name: 'retained-trace.zip', exact: true })
  await trace.getByRole('button', { name: 'Download', exact: true }).click()
  const download = page.getByRole('link', { name: 'Download retained-trace.zip', exact: true })
  const url = await download.getAttribute('href')
  expect(url).toMatch(/^http:\/\/127\.0\.0\.1:8041\/access\//)
  const bytes = await page.request.get(url!)
  expect(bytes.ok()).toBe(true)
  expect((await bytes.body()).subarray(0, 2).toString()).toBe('PK')
  expect((await api.call('GET', `${path}/runs/${first.id}/retention`)).pin.pinned).toBe(true)
  expect((await api.call('GET', `${path}/runs/${first.id}`)).data.release.id).toBe(first.release.id)
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(2)
  await page.getByRole('link', { name: 'TestStudio health', exact: true }).click()
  await expect(firstRow).toBeVisible()
  const session = await (await page.request.get('/auth/session')).json()
  await api.call('POST', `${path}/permissions`, { principalKind: 'user', principalId: session.session.userId, permission: 'teststudio.catalog.read', effect: 'deny', object: 'suite/health', reason: 'Verify current retained-history access' })
  await expectHTTPFailure(page, 'GET', `${base}/retained`, 403, () => page.getByRole('button', { name: 'Refresh history', exact: true }).click())
  await expect(page.getByRole('article', { name: /^Run / })).toHaveCount(0)
  await expect(page.getByRole('alert')).toBeVisible()
})
