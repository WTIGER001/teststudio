import { test, expect } from './fixtures'

test('The sidebar reports the immutable release and matches the running API build', { tag: '@STUDIO-VERSION-001' }, async ({ page, api }, testInfo) => {
  const metadata = await (await page.request.get('/api/v1/version')).json()
  const footer = page.getByRole('region', { name: 'Application build information' })
  await expect(footer).toContainText(metadata.displayVersion)
  expect(metadata.displayVersion).toMatch(/^\d+\.\d+\.\d+\.[a-z][a-z0-9-]*$/)
  expect(metadata.buildId).toMatch(/^[a-f0-9]{12}$/)
  expect(metadata.commit).toMatch(/^[a-f0-9]{40,64}$/)
  await expect(footer.locator('time')).toHaveAttribute('datetime', metadata.builtAt)
  await expect(footer).toContainText('UTC')
  await footer.getByText('Build ' + metadata.buildId, { exact: true }).click()
  await expect(footer).toContainText(metadata.version)
  await expect(footer).toContainText(metadata.commit)
  await expect(footer).toContainText(metadata.sourceHash)
  await testInfo.attach('sidebar-build-desktop', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await page.reload()
  await expect(footer).toContainText(metadata.buildId)
  await expect(footer.locator('time')).toHaveAttribute('datetime', metadata.builtAt)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Navigation', exact: true }).click()
  await expect(footer).toContainText(metadata.displayVersion)
  await expect(footer).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('sidebar-build-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
