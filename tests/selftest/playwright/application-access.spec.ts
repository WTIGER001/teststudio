import { test, expect, expectHTTPFailure, followNavigation } from './fixtures'

test('Standard membership review, application isolation, inherited access and conversion', { tag: '@STUDIO-APPLICATION-ACCESS-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  const user = 'standard-member', group = 'standard-team', appBase = `${path}/applications/app/role-assignments`
  await api.call('PUT', `${path}/applications/sibling`, { id: 'sibling', name: 'Sibling application' }, 0)
  await api.call('POST', '/api/v1/users', { id: user, name: 'Standard member' })
  await api.call('POST', '/api/v1/groups', { id: group, name: 'Standard team', projectId: project })
  await api.call('PUT', `/api/v1/groups/${group}/members/${user}`, {}, 0)
  const table = () => page.getByRole('table', { name: 'Role assignments in the selected scope', exact: true })
  const row = (id: string, role: string) => table().getByRole('row').filter({ has: page.getByText(id, { exact: true }) }).filter({ has: page.getByRole('cell', { name: role, exact: true }) })
  const fill = async (kind: 'user' | 'group', id: string, role: string) => {
    await page.getByRole('button', { name: '+ Add role', exact: true }).click()
    await page.getByLabel('Principal type', { exact: true }).selectOption(kind)
    await page.getByLabel('Registered principal identifier', { exact: true }).fill(id)
    await page.getByLabel('Role to assign', { exact: true }).selectOption(`builtin.teststudio.${role}`)
    await page.getByLabel('Assignment reason', { exact: true }).fill('Reviewed standard membership')
    await page.getByRole('button', { name: 'Review assignment', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Review role assignment', exact: true })).toBeFocused()
  }
  await test.step('Review a Project Member and change its role atomically', async () => {
    await page.goto(`/projects/${project}/members`)
    await fill('user', user, 'member')
    await expect(page.getByRole('heading', { name: 'Review role assignment' }).locator('..')).toContainText('Standard member')
    await page.getByRole('button', { name: 'Assign role', exact: true }).click()
    await expect(row(user, 'Member')).toBeVisible()
    await row(user, 'Member').getByRole('button', { name: 'Change role' }).click()
    await page.getByLabel('Role to assign', { exact: true }).selectOption('builtin.teststudio.reader')
    await page.getByLabel('Assignment reason', { exact: true }).fill('Reduce direct project powers')
    await page.getByRole('button', { name: 'Review assignment', exact: true }).click()
    await page.getByRole('button', { name: 'Save role', exact: true }).click()
    await expect(row(user, 'Reader')).toBeVisible()
    await expect(row(user, 'Member')).toHaveCount(0)
  })
  await test.step('Application membership distinguishes inherited project and group access', async () => {
    await page.goto(`/projects/${project}/applications/app/members`)
    await expect(page.getByRole('heading', { name: 'Application members', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Inherited project access' }).locator('..')).toContainText('Reader · From project · Read only here')
    await fill('group', group, 'developer')
    await page.getByRole('button', { name: 'Assign role', exact: true }).click()
    await expect(row(group, 'Developer')).toContainText('From group membership')
    expect((await api.call('GET', `${appBase}/group/${group}/builtin.teststudio.developer`)).applicationId).toBe('app')
    await fill('user', user, 'member')
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Application members help', exact: true })).toContainText('Direct and inherited access')
    await page.keyboard.press('Escape')
    await expect(page.getByLabel('Assignment reason', { exact: true })).toHaveValue('Reviewed standard membership')
    for (const theme of ['light', 'dark']) {
      await page.getByLabel('Color theme').selectOption(theme)
      await page.setViewportSize(theme === 'light' ? { width: 1280, height: 900 } : { width: 390, height: 844 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach(`application-members-${theme}`, { body: await page.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
    }
    page.once('dialog', dialog => dialog.dismiss())
    await followNavigation(page, 'Application overview')
    await expect(page.getByLabel('Assignment reason', { exact: true })).toHaveValue('Reviewed standard membership')
    await page.getByRole('button', { name: 'Assign role', exact: true }).click()
    await expect(row(user, 'Member')).toBeVisible()
    await page.setViewportSize({ width: 1280, height: 900 })
    await row(user, 'Member').getByRole('button', { name: 'Inspect access' }).click()
    await expect(page.getByRole('region', { name: 'Current decision', exact: true })).toContainText('Allowed')
    await expect(page.getByRole('region', { name: 'Permission sources', exact: true })).toContainText('Application binding')
    await page.goto(`/projects/${project}/applications/app/members`)
    await expect(row(user, 'Member')).toBeVisible()
    await page.getByLabel('Application', { exact: true }).selectOption('sibling')
    await expect(page.getByRole('heading', { name: 'Application members', exact: true })).toBeVisible()
    await expect(row(group, 'Developer')).toHaveCount(0)
    await expect(page.getByRole('heading', { name: 'Inherited project access' }).locator('..')).toContainText('Reader')
  })
  await test.step('Conversion requires a reviewed preview and offers reviewed rollback', async () => {
    await api.call('POST', `${path}/role-assignments`, { principalKind: 'user', principalId: user, roleId: 'builtin.teststudio.operator', reason: 'Compatibility fixture' })
    await page.goto(`/projects/${project}/members`)
    await row(user, 'Operator').getByRole('button', { name: 'Review conversion' }).click()
    await page.getByLabel('Target standard role').selectOption('builtin.teststudio.member')
    await page.getByLabel('Conversion reason', { exact: true }).fill('Adopt reviewed standard Member')
    await page.getByRole('button', { name: 'Preview conversion', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Conversion review', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Permissions removed' }).locator('..')).toContainText('teststudio.schedules.delete')
    await expect(row(user, 'Operator')).toBeVisible()
    await page.getByRole('button', { name: 'Apply reviewed conversion', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Conversion applied', exact: true })).toBeVisible()
    await expect(row(user, 'Member')).toBeVisible()
    await expect(row(user, 'Operator')).toHaveCount(0)
    await page.getByText('Advanced recovery', { exact: true }).click()
    await page.getByLabel('Rollback reason', { exact: true }).fill('Review restoring compatibility access')
    await page.getByRole('button', { name: 'Preview rollback', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Conversion review', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Apply reviewed conversion', exact: true }).click()
    await expect(row(user, 'Operator')).toBeVisible()
    await expect(row(user, 'Reader')).toBeVisible()
    await page.getByRole('button', { name: 'Close conversion', exact: true }).click()
  })
  await test.step('Application-only Contributor sees its scope and cannot change Owners', async () => {
    const response = await page.request.post('http://127.0.0.1:8050/access/prepare', { data: { project } })
    expect(response.ok()).toBe(true)
    const fixture = await response.json(), rootCookies = await page.context().cookies()
    const oldPath = `${path}/role-assignments/user/${fixture.userId}/builtin.teststudio.project-admin`
    const old = await api.call('GET', oldPath)
    await api.call('DELETE', oldPath, { reason: 'Use only application scope' }, old.revision)
    await api.call('POST', appBase, { principalKind: 'user', principalId: fixture.userId, roleId: 'builtin.teststudio.contributor', reason: 'Application-only manager' })
    const prior = await api.call('GET', `${appBase}/user/${user}/builtin.teststudio.member`)
    await api.call('PUT', `${appBase}/user/${user}`, { previousRoleId: 'builtin.teststudio.member', roleId: 'builtin.teststudio.owner', reason: 'Owner guard fixture' }, prior.revision)
    try {
      await page.context().addCookies([{ name: 'teststudio_session', value: fixture.cookie, domain: '127.0.0.1', path: '/', httpOnly: true, sameSite: 'Lax', secure: false }])
      await page.goto(`/projects/${project}/applications/app/members`)
      await expect(row(fixture.userId, 'Contributor')).toBeVisible()
      await expect(row(user, 'Owner')).toContainText('Read only')
      await expect(row(user, 'Owner').getByRole('button', { name: 'Change role' })).toHaveCount(0)
      const nav = page.getByRole('navigation', { name: 'Main navigation', includeHidden: true })
      await expect(nav.getByRole('link', { name: 'Project members', exact: true, includeHidden: true })).toHaveCount(0)
      await expect(nav.getByRole('link', { name: 'System access', exact: true, includeHidden: true })).toHaveCount(0)
      await page.getByRole('button', { name: '+ Add role', exact: true }).click()
      await expect(page.getByLabel('Role to assign', { exact: true }).getByRole('option', { name: 'Owner · Read only', exact: true })).toBeDisabled()
      await page.getByRole('button', { name: 'Close assignment editor', exact: true }).click()
      await expectHTTPFailure(page, 'GET', `/api/v1/me/capabilities?project=${project}&application=sibling`, 403, () => page.goto(`/projects/${project}/applications/sibling/members`), { allowRepeated: true })
      await expect(page.getByRole('alert')).toContainText('Membership and permission read authority is required')
      await expect(table().getByRole('row')).toHaveCount(1)
    } finally { await page.context().addCookies(rootCookies); await page.goto(`/projects/${project}/members`) }
  })
})
