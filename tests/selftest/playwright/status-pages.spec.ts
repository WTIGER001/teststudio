test('Public status draft publication, embeds, private-data boundaries and availability', { tag: '@STUDIO-STATUS-PAGES-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path); await api.run(path)
  await api.call('PUT', `${path}/environments/second`, { id: 'second', name: 'Second target', applicationId: 'app', stage: 'local', endpoints: { api: 'http://127.0.0.1:8040' } }, 0)
  const probe = await api.call('POST', `${path}/probes`, { name: 'Private target name', suiteId: 'health', testId: 'SELF-CHECK', environmentId: 'local', endpoint: 'api', executionLocation: 'local', archived: false })
  const second = await api.call('POST', `${path}/probes`, { name: 'Second target name', suiteId: 'health', testId: 'SELF-CHECK', environmentId: 'second', endpoint: 'api', executionLocation: 'local', archived: false })
  await page.goto(`/projects/${project}/status-pages`)
  await page.getByRole('link', { name: 'Create status page', exact: true }).click()
  await page.getByLabel('Page title', { exact: true }).fill('Customer service status')
  await page.getByLabel('Vanity URL (optional)', { exact: true }).fill('Customer-Services')
  await expect(page.getByText('Available for this page. Reserved when you save.', { exact: true })).toBeVisible()
  await page.getByLabel('Background color', { exact: true }).fill('#ffffff')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Status pages help' })).toContainText('Time-based availability')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Page title', { exact: true })).toHaveValue('Customer service status')
  page.once('dialog', dialog => dialog.dismiss())
  await followNavigation(page, 'Status pages')
  await expect(page.getByLabel('Page title', { exact: true })).toHaveValue('Customer service status')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Add HTTP probe', { exact: true }).selectOption(probe.id)
  await page.getByLabel('Public title 1', { exact: true }).fill('Public website')
  await page.getByLabel('Description 1 (optional)', { exact: true }).fill('Customer website availability')
  await page.getByLabel('Add HTTP probe', { exact: true }).selectOption(second.id)
  await page.getByLabel('Public title 2', { exact: true }).fill('Secondary service')
  await page.getByRole('button', { name: 'Move probe 2 up', exact: true }).click()
  await expect(page.getByLabel('Public title 1', { exact: true })).toHaveValue('Secondary service')
  await page.getByRole('button', { name: 'Move probe 1 down', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Edit status page', exact: true })).toBeVisible()
  await expect(page.getByLabel('Page title', { exact: true })).toHaveCount(0)
  const id = page.url().split('/').at(-1)!, base = `${path}/status-pages/${id}`
  const record = await api.call('GET', base), token = record.data.publicToken, publicPath = `/api/v1/public/status-pages/${record.data.slug}`
  await testInfo.attach('status-page-details', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await page.goto(`/projects/${project}/status-pages/new`)
  await page.getByLabel('Page title', { exact: true }).fill('Another page')
  await page.getByLabel('Vanity URL (optional)', { exact: true }).fill('CUSTOMER-SERVICES')
  await expect(page.getByText('That name is already reserved. Choose another.', { exact: true })).toBeVisible()
  await page.getByLabel('Page title', { exact: true }).fill('Another title')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByLabel('Page title', { exact: true })).toBeVisible()
  await page.getByLabel('Vanity URL (optional)', { exact: true }).fill('another-service')
  await expect(page.getByText('Available for this page. Reserved when you save.', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('status-page-appearance-narrow', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await page.setViewportSize({ width: 1280, height: 900 })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('link', { name: 'Cancel setup', exact: true }).click()
  await page.goto(`/projects/${project}/status-pages/${id}`)
  const anonymous = await page.context().browser()!.newContext()
  const visitor = await anonymous.newPage()
  const requests: string[] = [], runtimeErrors: string[] = []
  visitor.on('pageerror', error => runtimeErrors.push(error.message))
  visitor.on('console', message => { if (message.type() === 'error') runtimeErrors.push(message.text()) })
  visitor.on('request', request => requests.push(new URL(request.url()).pathname))
  try {
    expect((await anonymous.request.get(publicPath.replace('/api/v1/public/status-pages/', 'http://127.0.0.1:8040/api/v1/public/status-pages/'))).status()).toBe(404)
    await page.getByRole('link', { name: 'Review publication', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Public preview', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Confirm publish', exact: true })).toBeVisible()
    await testInfo.attach('status-page-publication-review', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
    await page.getByRole('button', { name: 'Confirm publish', exact: true }).click()
    await expect(page.getByLabel('Public URL', { exact: true })).toBeVisible()
    const url = await page.getByLabel('Public URL', { exact: true }).inputValue()
    await expect(page.getByLabel('Iframe embed code', { exact: true })).toHaveValue(/iframe/)
    await visitor.goto(url)
    await expect(visitor.getByRole('heading', { name: 'Customer service status', exact: true })).toBeVisible()
    await expect(visitor.getByRole('article')).toHaveCount(2)
    await expect(visitor.getByRole('article', { name: 'Public website', exact: true })).toContainText('100.00%')
    await expect(visitor.getByRole('article', { name: 'Secondary service', exact: true })).toContainText('No data')
    await expect(visitor.getByRole('navigation', { name: 'Main navigation', includeHidden: true })).toHaveCount(0)
    await expect(visitor.getByRole('button', { name: 'Open local workspace' })).toHaveCount(0)
    expect(requests.some(path => path.startsWith('/auth/') || path === '/api/v1/projects')).toBe(false)
    const pill = visitor.getByRole('article', { name: 'Public website', exact: true }).locator('.pill').first()
    await pill.hover(); await expect(pill.getByRole('tooltip')).toContainText('Available')
    await pill.focus(); await expect(pill).toBeFocused()
    for (const window of ['7d', '1m', '1y', 'all', '24h']) {
      await Promise.all([visitor.waitForResponse(response => response.url().includes(publicPath + '?window=' + window) && response.ok()), visitor.getByLabel('Availability period', { exact: true }).selectOption(window)])
      await expect(visitor.getByLabel('Availability period', { exact: true })).toHaveValue(window)
      await expect(visitor.getByRole('article')).toHaveCount(2)
    }
    for (const size of [{ width: 1280, height: 900 }, { width: 390, height: 844 }]) {
      await visitor.setViewportSize(size)
      expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach(`public-status-${size.width}`, { body: await visitor.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
    }
    const host = await anonymous.newPage()
    try {
      await host.goto('http://127.0.0.1:8050/status-host/' + token)
      await expect(host.frameLocator('iframe[title="Embedded public status"]').getByRole('heading', { name: 'Customer service status', exact: true })).toBeVisible()
      await expect(host.frameLocator('iframe[title="Embedded public status"]').getByRole('article')).toHaveCount(2)
    } finally { await host.close() }
    const darkDefinition = { id: 'dark-status', title: 'Dark service status', background: '#101827', defaultWindow: '1y', maxAgeSeconds: 900, probes: [{ probeId: probe.id, title: 'Public website', description: 'Customer website availability' }] }
    await api.call('PUT', `${path}/status-pages/dark-status`, darkDefinition, 0)
    const darkPage = await api.call('POST', `${path}/status-pages/dark-status/publish`, undefined, 1)
    await visitor.goto('http://127.0.0.1:8040/status/' + darkPage.data.publicToken)
    await expect(visitor.getByRole('heading', { name: 'Dark service status', exact: true })).toBeVisible()
    await expect(visitor.getByLabel('Availability period', { exact: true })).toHaveValue('1y')
    await expect(visitor.getByRole('article')).toContainText('<0.1% monitored')
    for (const width of [1280, 390]) {
      await visitor.setViewportSize({ width, height: 900 })
      expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach(`public-status-dark-${width}`, { body: await visitor.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
    }
    const report = await (await anonymous.request.get('http://127.0.0.1:8040' + publicPath)).json()
    const text = JSON.stringify(report)
    for (const privateValue of [project, probe.id, 'Private target name', 'http://127.0.0.1', 'environmentId', 'runId', 'publicToken']) expect(text).not.toContain(privateValue)
    await page.getByRole('link', { name: 'Edit status page', exact: true }).click()
    await page.getByLabel('Page title', { exact: true }).fill('Private changed title')
    await page.getByLabel('Vanity URL (optional)', { exact: true }).fill('renamed-services')
    await page.getByRole('button', { name: 'Continue', exact: true }).click(); await page.getByRole('button', { name: 'Continue', exact: true }).click()
    await page.getByRole('button', { name: 'Save draft', exact: true }).click()
    await expect.poll(async () => (await api.call('GET', base)).data.title).toBe('Private changed title')
    await visitor.goto(url)
    await expect(visitor.getByRole('heading', { name: 'Customer service status', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Review publication', exact: true }).click()
    await expect(page.getByText('The vanity URL changes on publication.', { exact: false })).toBeVisible()
    await page.getByRole('button', { name: 'Confirm publish', exact: true }).click()
    await expect(page.getByLabel('Public URL', { exact: true })).toHaveValue(/\/status\/renamed-services$/)
    expect((await anonymous.request.get('http://127.0.0.1:8040' + publicPath)).status()).toBe(404)
    expect((await anonymous.request.get('http://127.0.0.1:8040/api/v1/public/status-pages/' + token)).status()).toBe(200)
    await visitor.goto('http://127.0.0.1:8040/status/renamed-services')
    await expect(visitor.getByRole('heading', { name: 'Private changed title', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Edit status page', exact: true }).click()
    await page.getByLabel('Page title', { exact: true }).fill('Retained conflict input')
    const current = await api.call('GET', base)
    await api.call('PUT', base, { ...current.data, publicToken: undefined, published: undefined, publishedAt: undefined, publisher: undefined, title: 'Concurrent draft' }, current.revision)
    await page.getByRole('button', { name: 'Continue', exact: true }).click(); await page.getByRole('button', { name: 'Continue', exact: true }).click()
    await expectHTTPFailure(page, 'PUT', base, 409, () => page.getByRole('button', { name: 'Save draft', exact: true }).click())
    await expect(page.getByRole('button', { name: 'Save draft', exact: true })).toBeDisabled()
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'Reload saved page', exact: true }).click()
    await expect(page.getByLabel('Page title', { exact: true })).toHaveValue('Concurrent draft')
    await page.getByRole('link', { name: 'Cancel editing', exact: true }).click()
    await page.getByText('Page actions', { exact: true }).click()
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'Unpublish', exact: true }).click()
    await expect(page.getByText('Public access withdrawn. Your draft remains.', { exact: true })).toBeVisible()
    expect((await anonymous.request.get('http://127.0.0.1:8040/api/v1/public/status-pages/renamed-services')).status()).toBe(404)
    expect(runtimeErrors).toEqual([])
  } finally { await anonymous.close() }
})
