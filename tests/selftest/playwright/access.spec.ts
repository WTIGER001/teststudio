import { request } from '@playwright/test'
import { test, expect, expectHTTPFailure, followNavigation, navigationLink } from './fixtures'

test.use({ timezoneId: 'America/Los_Angeles' })

test('Identity administration, scoped groups, and session controls', { tag: '@STUDIO-ACCESS-001' }, async ({ page, api }, testInfo) => {
  const { project } = await api.scaffold(), other = await api.scaffold()
  const user = 'reviewer', userPath = `/api/v1/users/${user}`, group = 'reviewers', groupPath = `/api/v1/groups/${group}`
  const userTable = () => page.getByRole('table', { name: 'Installation users', exact: true })
  const memberTable = () => page.getByRole('table', { name: 'Group membership records', exact: true })
  const memberRow = () => memberTable().getByRole('row').filter({ has: page.getByText(user, { exact: true }) })
  const status = (value: RegExp) => page.getByRole('status').filter({ hasText: value })
  const future = (days: number) => { const value = new Date(Date.now() + days * 86400000); value.setUTCSeconds(12, 0); return value.toISOString() }
  const confirm = async (reason: string) => { await page.getByLabel('Reason', { exact: true }).fill(reason); await page.getByRole('button', { name: 'Confirm action', exact: true }).click() }

  await test.step('Register a pending profile without identity linking or access grants', async () => {
    await page.goto('/settings/users')
    await page.getByRole('button', { name: '+ Register user', exact: true }).click()
    await page.getByLabel('Display name', { exact: true }).fill('Review operator')
    await page.getByLabel('User identifier', { exact: true }).fill(user)
    await page.getByLabel('Email address (optional)', { exact: true }).fill('reviewer@example.test')
    await page.getByRole('button', { name: 'Save user profile', exact: true }).click()
    await expect(status(/^User profile registered/)).toBeVisible()
    await userTable().getByRole('link', { name: 'Review operator', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'User details', exact: true })).toBeVisible()
    await expect(page.getByText(/No readable linked identities in this page/)).toBeVisible()
    const profile = await api.call('GET', userPath)
    expect(profile.data.emailVerified).toBe(false)
    expect((await api.call('GET', `${userPath}/memberships`)).items).toHaveLength(0)
  })

  await test.step('Keep unsaved profile edits on a genuine revision conflict and reload explicitly', async () => {
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
    await page.getByLabel('Display name', { exact: true }).fill('Unsaved local edit')
    const before = await api.call('GET', userPath)
    await api.call('PUT', userPath, { id: user, name: 'Concurrent profile edit', email: 'reviewer@example.test' }, before.revision)
    await expectHTTPFailure(page, 'PUT', userPath, 409, () => page.getByRole('button', { name: 'Save user profile', exact: true }).click())
    await expect(page.getByLabel('Display name', { exact: true })).toHaveValue('Unsaved local edit')
    await expect(page.getByText(/The profile changed. Your edits remain here/)).toBeVisible()
    await page.getByRole('button', { name: 'Reload stored profile', exact: true }).click()
    await expect(page.getByLabel('Display name', { exact: true })).toHaveValue('Concurrent profile edit')
    await page.getByLabel('Display name', { exact: true }).fill('Reviewed operator')
    await page.getByRole('button', { name: 'Save user profile', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Reviewed operator', exact: true })).toBeVisible()
  })

  await test.step('Disable and restore through explicit reasons while retaining the profile', async () => {
    await page.getByRole('button', { name: 'Disable user', exact: true }).click()
    await confirm('Reviewing this account')
    await expect(status(/^User disabled/)).toBeVisible()
    expect((await api.call('GET', userPath)).data.disabled).toBe(true)
    await page.getByRole('button', { name: 'Restore user', exact: true }).click()
    await confirm('Account review complete')
    await expect(status(/^User restored/)).toBeVisible()
    expect((await api.call('GET', userPath)).data.disabled).toBe(false)
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
    await page.getByLabel('Display name', { exact: true }).fill('Unsaved user note')
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'User details help', exact: true })).toContainText('Session revocation')
    await page.keyboard.press('Escape')
    await expect(page.getByLabel('Display name', { exact: true })).toHaveValue('Unsaved user note')
    for (const theme of ['light', 'dark']) {
      await page.getByLabel('Color theme').selectOption(theme)
      await page.setViewportSize(theme === 'light' ? { width: 1280, height: 900 } : { width: 390, height: 844 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach(`user-details-${theme}`, { body: await page.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
    }
    await page.getByRole('button', { name: 'Close editor', exact: true }).click()
    await page.setViewportSize({ width: 1280, height: 900 })
  })

  await test.step('Create distinct installation and project groups with permanent scope', async () => {
    await followNavigation(page, 'Installation groups')
    await page.getByRole('button', { name: '+ New group', exact: true }).click()
    await page.getByLabel('Group name', { exact: true }).fill('Shared reviewers')
    await page.getByLabel('Group identifier', { exact: true }).fill('shared-reviewers')
    await page.getByRole('button', { name: 'Save group', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Shared reviewers', exact: true })).toBeVisible()
    await page.goto(`/projects/${project}/groups`)
    await expect(page.getByRole('link', { name: 'Shared reviewers', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '+ New group', exact: true }).click()
    await page.getByLabel('Group name', { exact: true }).fill('Project reviewers')
    await page.getByLabel('Group identifier', { exact: true }).fill(group)
    await page.getByLabel('Description (optional)', { exact: true }).fill('Local review membership')
    await page.getByRole('button', { name: 'Save group', exact: true }).click()
    await page.getByRole('link', { name: 'Project reviewers', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Group details', exact: true })).toBeVisible()
    expect((await api.call('GET', groupPath)).data.projectId).toBe(project)
  })

  await test.step('Add local membership, edit UTC expiry, and recover from a real membership conflict', async () => {
    await page.getByRole('button', { name: '+ Add member', exact: true }).click()
    await page.getByLabel('Registered user identifier', { exact: true }).fill(user)
    const initial = future(1)
    await page.getByLabel('Membership expiry (UTC, optional)', { exact: true }).fill(initial.slice(0, 19))
    await page.getByRole('button', { name: 'Save local membership', exact: true }).click()
    await expect(memberRow()).toContainText('Locally managed')
    expect(Date.parse((await api.call('GET', `${groupPath}/members/${user}`)).data.expiresAt)).toBe(Date.parse(initial))
    await memberRow().getByRole('button', { name: 'Edit membership', exact: true }).click()
    const desired = future(3).slice(0, 19), stored = future(2)
    await page.getByLabel('Membership expiry (UTC, optional)', { exact: true }).fill(desired)
    const before = await api.call('GET', `${groupPath}/members/${user}`)
    await api.call('PUT', `${groupPath}/members/${user}`, { expiresAt: stored }, before.revision)
    await expectHTTPFailure(page, 'PUT', `${groupPath}/members/${user}`, 409, () => page.getByRole('button', { name: 'Save local membership', exact: true }).click())
    await expect(page.getByLabel('Membership expiry (UTC, optional)', { exact: true })).toHaveValue(desired)
    await page.getByRole('button', { name: 'Reload stored membership', exact: true }).click()
    await expect(page.getByLabel('Membership expiry (UTC, optional)', { exact: true })).toHaveValue(stored.slice(0, 19))
    await page.getByLabel('Membership expiry (UTC, optional)', { exact: true }).fill('')
    await page.getByRole('button', { name: 'Save local membership', exact: true }).click()
    await expect(memberRow()).toContainText('No expiry')
    const saved = await api.call('GET', `${groupPath}/members/${user}`)
    expect(saved.data.expiresAt).toBeUndefined(); expect(saved.data.source).toBe('local')
    await page.goto(`/settings/users/${user}`)
    await page.getByRole('table', { name: 'User group memberships', exact: true }).getByRole('link', { name: 'Project reviewers', exact: true }).click()
    await expect(memberRow()).toContainText('Active')
  })

  await test.step('Archive and restore retained membership, preserving help and responsive edits', async () => {
    await page.getByRole('button', { name: 'Archive group', exact: true }).click()
    await confirm('Review group access')
    await expect(memberRow()).toContainText('Inactive')
    await expect(page.getByRole('button', { name: '+ Add member', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Restore group', exact: true }).click()
    await confirm('Retained membership approved')
    await expect(memberRow()).toContainText('Active')
    await page.getByRole('button', { name: 'Edit group', exact: true }).click()
    await page.getByLabel('Description (optional)', { exact: true }).fill('Unsaved group note')
    await memberRow().getByRole('button', { name: 'Edit membership', exact: true }).click()
    const expiry = future(4).slice(0, 19)
    await page.getByLabel('Membership expiry (UTC, optional)', { exact: true }).fill(expiry)
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Group details help', exact: true })).toContainText('UTC expiry')
    await page.keyboard.press('Escape')
    await expect(page.getByLabel('Description (optional)', { exact: true })).toHaveValue('Unsaved group note')
    await expect(page.getByLabel('Membership expiry (UTC, optional)', { exact: true })).toHaveValue(expiry)
    for (const theme of ['light', 'dark']) {
      await page.getByLabel('Color theme').selectOption(theme)
      await page.setViewportSize(theme === 'light' ? { width: 1280, height: 900 } : { width: 390, height: 844 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach(`group-details-${theme}`, { body: await page.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
    }
    await page.getByRole('button', { name: 'Close membership editor', exact: true }).click()
    await page.getByRole('button', { name: 'Close editor', exact: true }).click()
    await memberRow().getByRole('button', { name: 'Remove member', exact: true }).click()
    await confirm('   ')
    await expect(page.getByRole('alert')).toContainText('Enter a reason')
    await confirm('Review membership removed')
    await expect(memberRow()).toHaveCount(0)
  })

  await test.step('Reset old scope editors and continue bounded directory pages', async () => {
    await api.call('POST', '/api/v1/groups', { id: 'other-reviewers', name: 'Other reviewers', projectId: other.project })
    await page.getByRole('button', { name: 'Edit group', exact: true }).click()
    await page.getByLabel('Group name', { exact: true }).fill('Unsaved scope change')
    await page.getByLabel('Project', { exact: true }).selectOption(other.project)
    await followNavigation(page, 'Project groups')
    await expect(page.getByRole('heading', { name: 'Edit group', exact: true })).toHaveCount(0)
    await expect(page.getByRole('link', { name: 'Other reviewers', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Project reviewers', exact: true })).toHaveCount(0)
    expect((await api.call('GET', groupPath)).data.name).toBe('Project reviewers')
    for (let index = 0; index < 31; index++) await api.call('POST', '/api/v1/users', { id: `zz-reviewer-${index}`, name: `Directory reviewer ${index}` })
    await followNavigation(page, 'Users')
    await expect(userTable().getByRole('row')).toHaveCount(31)
    await page.getByRole('button', { name: 'More users', exact: true }).click()
    await expect(userTable().getByRole('row')).toHaveCount(34)
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Users help', exact: true })).toContainText('Pending profiles')
    await page.keyboard.press('Escape')
  })

  await test.step('Protect the final administrator and revoke another real session without signing this browser out', async () => {
    const otherSession = await request.newContext({ baseURL: 'http://127.0.0.1:8040' })
    try {
      expect((await otherSession.post('/auth/local', { headers: { Origin: 'http://127.0.0.1:8040' }, data: {} })).ok()).toBe(true)
      await page.goto('/settings/users/local-administrator')
      await page.getByRole('button', { name: 'Disable user', exact: true }).click()
      await page.getByLabel('Reason', { exact: true }).fill('Reject final administrator removal')
      await expectHTTPFailure(page, 'POST', '/api/v1/users/local-administrator/disable', 422, () => page.getByRole('button', { name: 'Confirm action', exact: true }).click())
      await expect(page.getByRole('alert')).toContainText('last usable installation administrator')
      await page.getByRole('button', { name: 'Cancel action', exact: true }).click()
      const sessions = (await api.call('GET', '/api/v1/users/local-administrator/sessions')).items
      expect(sessions).toHaveLength(2)
      const second = sessions.find((item: any) => !item.data.current)
      expect(second).toBeTruthy()
      const row = page.getByRole('table', { name: 'User active sessions', exact: true }).getByRole('row').filter({ hasText: second.id })
      await row.getByRole('button', { name: 'Revoke session', exact: true }).click()
      await confirm('End the separate verification session')
      await expect(row).toHaveCount(0)
      expect((await otherSession.get('/api/v1/me')).status()).toBe(401)
      await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
    } finally { await otherSession.dispose() }
  })

  await test.step('Enforce project administrator navigation and real external membership restrictions', async () => {
    const original = await page.context().cookies('http://127.0.0.1:8040')
    const response = await page.request.post('http://127.0.0.1:8050/access/prepare', { data: { project } })
    expect(response.ok()).toBe(true)
    const fixture = await response.json()
    try {
      await page.context().addCookies([{ name: 'teststudio_session', value: fixture.cookie, domain: '127.0.0.1', path: '/', httpOnly: true, sameSite: 'Lax', secure: false }])
      await page.goto(`/projects/${project}/groups/${fixture.groupId}`)
      await expect(page.getByRole('heading', { name: 'Provider reviewers', exact: true })).toBeVisible()
      await expect(memberTable()).toContainText('oidc:browser-fixture')
      await expect(memberTable()).toContainText('Externally managed · Read only')
      await expect(page.getByRole('button', { name: '+ Add member', exact: true })).toHaveCount(0)
      await expect(page.getByRole('button', { name: 'Edit membership', exact: true })).toHaveCount(0)
      const navigation = page.getByRole('navigation', { name: 'Main navigation' })
      await expect(await navigationLink(page, 'Project groups')).toBeVisible()
      await expect(navigation.getByRole('link', { name: 'Users', exact: true, includeHidden: true })).toHaveCount(0)
      await expect(navigation.getByRole('link', { name: 'Installation groups', exact: true, includeHidden: true })).toHaveCount(0)
      expect((await page.request.get('/api/v1/users')).status()).toBe(403)
      expect((await page.request.get(`/api/v1/groups?project=${other.project}`)).status()).toBe(403)
      expect((await page.request.get('/api/v1/groups/shared-reviewers')).status()).toBe(403)
      expect((await page.request.get('/api/v1/me')).ok()).toBe(true)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await testInfo.attach('external-membership-dark', { body: await page.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
      await page.goto('/settings/users')
      await expect(page.getByRole('alert')).toContainText('Installation user read permission is required')
      await expect(page.getByRole('button', { name: '+ Register user', exact: true })).toHaveCount(0)
      await expect(page.getByText('Local administrator', { exact: true })).toHaveCount(0)
      await page.goto(`/projects/${other.project}/groups`)
      await expect(page.getByRole('alert')).toContainText('Group read permission is required')
      await expect(page.getByRole('link', { name: 'Other reviewers', exact: true })).toHaveCount(0)
    } finally {
      await page.context().addCookies(original)
      await page.goto('/settings/users')
    }
    await expect(page.getByRole('button', { name: '+ Register user', exact: true })).toBeVisible()
  })
})
