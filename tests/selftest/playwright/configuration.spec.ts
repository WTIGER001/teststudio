import { test, expect, expectHTTPFailure } from './fixtures'

test('Application requirements and environment readiness preserve review, conflicts, and optional execution', { tag: '@STUDIO-CONFIG-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  const base = `${path}/applications/app`
  await page.goto(`/projects/${project}/applications/app`)
  await page.getByRole('link', { name: 'Environment configuration', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Environment configuration', exact: true })).toBeVisible()
  await expect(page.getByText('No requirements yet. Add application requirements or save tests that declare the configuration they use.', { exact: true })).toBeVisible()
  await api.createCheck(path)
  await page.getByRole('button', { name: 'Reload configuration', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Required configuration by environment' })).toContainText('api')
  await page.getByRole('button', { name: 'Edit requirements', exact: true }).click()
  await page.getByRole('button', { name: 'Add requirement', exact: true }).click()
  await page.getByLabel('Configuration name', { exact: true }).fill('tenantId')
  await page.getByLabel('Value type', { exact: true }).selectOption('integer')
  await page.getByLabel('Required for every run against an environment').check()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Environment configuration help', exact: true })
  for (const title of ['Introduction', 'Concepts', 'Tutorials']) await expect(help.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Configuration name', { exact: true })).toHaveValue('tenantId')
  await page.getByRole('button', { name: 'Review requirements', exact: true }).click()
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click()
  const matrix = page.getByRole('table', { name: 'Required configuration by environment' })
  await expect(matrix.getByRole('row').filter({ hasText: 'tenantId' })).toContainText('missing')
  const session = (await (await page.request.get('/auth/session')).json()).session
  const blocked = await page.request.post(`${path}/runs`, { headers: { Origin: 'http://127.0.0.1:8040', 'X-CSRF-Token': session.csrfToken, 'Idempotency-Key': crypto.randomUUID() }, data: { suiteId: 'health', environmentId: 'local', testIds: ['SELF-CHECK'] } })
  expect(blocked.status()).toBe(422)
  await page.getByRole('button', { name: 'Configure Self-test instance', exact: true }).click()
  await page.getByLabel('tenantId · Parameter', { exact: true }).fill('42')
  await page.getByRole('button', { name: 'Review environment configuration', exact: true }).click()
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await expect(matrix.getByRole('row').filter({ hasText: 'tenantId' })).toContainText('ready')
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(0)
  await api.run(path)
  await page.getByRole('button', { name: 'Configure Self-test instance', exact: true }).click()
  await page.getByLabel('tenantId · Parameter', { exact: true }).fill('43')
  const current = await api.call('GET', `${base}/configuration`)
  const environment = current.environments[0]
  await api.call('PUT', `${base}/environments/local/configuration`, { endpoints: environment.data.endpoints, parameters: { tenantId: '44' }, credentialBindings: {} }, environment.revision)
  await page.getByRole('button', { name: 'Review environment configuration', exact: true }).click()
  await expectHTTPFailure(page, 'PUT', `${base}/environments/local/configuration`, 409, () => page.getByRole('button', { name: 'Save configuration', exact: true }).click())
  await expect(page.getByRole('alert')).toContainText('Your edits remain here')
  await expect(page.getByLabel('tenantId · Parameter', { exact: true })).toHaveValue('43')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('link', { name: '← Application', exact: true }).click()
  await expect(page).toHaveURL(`/projects/${project}/applications/app/configuration`)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Reload configuration', exact: true }).click()
  await page.getByRole('button', { name: 'Configure Self-test instance', exact: true }).click()
  await expect(page.getByLabel('tenantId · Parameter', { exact: true })).toHaveValue('44')
  await page.getByRole('button', { name: 'Cancel configuration changes', exact: true }).click()
  await page.getByLabel('Color theme').selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('environment-configuration-dark-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
