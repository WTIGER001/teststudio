import { test, expect, API, followNavigation } from './fixtures'

test('Ordinary project creators finish setup, publish tests and delegate only project access', { tag: '@STUDIO-OWNER-001' }, async ({ page, api }, testInfo) => {
  const foreign = await api.scaffold()
  await api.call('POST', '/api/v1/users', { id: 'project-member', name: 'Project member' })
  const response = await page.request.post('http://127.0.0.1:8050/access/creator', { data: { project: foreign.project } })
  expect(response.ok()).toBe(true)
  const creator = await response.json()
  await page.context().addCookies([{ name: 'teststudio_session', value: creator.cookie, domain: '127.0.0.1', path: '/', httpOnly: true, sameSite: 'Lax', secure: false }])
  await page.goto('/projects')
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /Self-test workspace/ })).toHaveCount(0)
  const session = await (await page.request.get('/auth/session')).json(), ownAPI = new API(page.request, session.session.csrfToken)
  await page.getByRole('link', { name: 'Create project', exact: true }).click()
  await expect(page).toHaveURL('/projects/new')
  const setup = page.locator('ts-project-setup')
  await setup.getByLabel('Project name', { exact: true }).fill('Creator workspace')
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await setup.getByLabel('Add a target environment now', { exact: true }).check()
  await setup.getByLabel('Base URL', { exact: true }).fill('http://127.0.0.1:8040')
  await setup.getByLabel('Stage', { exact: true }).selectOption('local')
  await setup.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(setup).toContainText('project administration, test editing, publishing, and run access')
  await setup.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'What type of test?', exact: true })).toBeVisible()
  const project = new URL(page.url()).pathname.split('/')[2], path = `/api/v1/projects/${project}`
  expect(project).not.toBe(foreign.project)
  const projects = (await ownAPI.call('GET', '/api/v1/projects')).items
  expect(projects.map((row: any) => row.id)).toEqual([project])
  const initial = (await ownAPI.call('GET', `${path}/role-assignments`)).items
  expect(initial).toHaveLength(4)
  expect(initial.every((row: any) => row.data.managed && row.data.principalId === creator.userId && row.data.bindingValues.team === project)).toBe(true)
  const installation = await ownAPI.call('GET', '/api/v1/me/capabilities')
  for (const permission of ['system.manage', 'users.manage', 'providers.manage', 'permissions.grant']) expect(installation[`teststudio.${permission}`]).toBe(false)
  await page.getByRole('link', { name: 'HTTPS probe', exact: true }).click()
  const probe = page.locator('ts-https-wizard')
  await probe.getByLabel('Title', { exact: true }).fill('Creator availability check')
  await probe.getByRole('button', { name: 'Continue', exact: true }).click()
  await probe.getByLabel('Website URL', { exact: true }).fill('http://127.0.0.1:8040/healthz')
  await probe.getByRole('button', { name: 'Continue', exact: true }).click()
  await probe.getByRole('button', { name: 'Save and run', exact: true }).click()
  const results = page.getByRole('region', { name: 'Final test results', exact: true })
  await expect(results.getByRole('cell', { name: 'passed', exact: true })).toBeVisible({ timeout: 20000 })
  await followNavigation(page, 'Project members')
  await expect(page.getByRole('heading', { name: 'Project members', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '+ Add role', exact: true }).click()
  await page.getByLabel('Principal type', { exact: true }).selectOption('user')
  await page.getByLabel('Registered principal identifier', { exact: true }).fill('project-member')
  await page.getByLabel('Role to assign', { exact: true }).selectOption('builtin.teststudio.viewer')
  await page.getByLabel('Assignment reason', { exact: true }).fill('Allow project review')
  await page.getByRole('button', { name: 'Assign role', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'project-member' })).toContainText('Viewer')
  expect((await ownAPI.call('GET', `${path}/role-assignments/user/project-member/builtin.teststudio.viewer`)).data.bindingValues).toEqual({ team: project })
  await testInfo.attach('project-owner-access', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
