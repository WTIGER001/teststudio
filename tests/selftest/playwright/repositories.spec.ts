import { test, expect } from './fixtures'

test('repository sources register multiple suites and queue durable syncs', { tag: '@STUDIO-GIT-001' }, async ({ page, api }) => {
  const { project, path } = await api.scaffold()
  for (const suite of ['unit', 'math']) await api.call('PUT', `${path}/suites/${suite}`, { id: suite, name: `${suite} checks`, applications: [], requiresTarget: false }, 0)
  await page.goto(`/projects/${project}/sources`)
  await page.getByRole('button', { name: 'Register repository', exact: true }).click()
  await page.getByLabel('Source identifier', { exact: true }).fill('application-tests')
  await page.getByLabel('Source name', { exact: true }).fill('Application tests')
  await page.getByLabel('GitHub repository', { exact: true }).fill('example/application')
  await page.getByLabel('Reference name or commit', { exact: true }).fill('feature/checks')
  await page.getByLabel('Suite 1', { exact: true }).selectOption('unit')
  await page.getByLabel('Manifest path 1', { exact: true }).fill('testing/unit.json')
  await page.getByRole('button', { name: 'Add suite binding', exact: true }).click()
  await page.getByLabel('Suite 2', { exact: true }).selectOption('math')
  await page.getByLabel('Manifest path 2', { exact: true }).fill('testing/math.json')
  await page.getByRole('button', { name: 'Save repository source', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Repository source saved' })).toBeVisible()
  let source = await api.call('GET', `${path}/repository-sources/application-tests`)
  expect(source.data.configuration.bindings).toHaveLength(2)
  expect(source.data.configuration.reference).toBe('heads/feature/checks')
  expect((await api.call('GET', `${path}/repository-sources/application-tests/syncs`)).items).toEqual([])
  expect((await api.call('GET', `${path}/runs`)).items).toEqual([])
  await page.getByRole('button', { name: 'Edit repository Application tests', exact: true }).click()
  await expect(page.getByLabel('Source identifier', { exact: true })).toBeDisabled()
  await page.getByLabel('Enable repository synchronization', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Save repository source', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sync now', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Edit repository Application tests', exact: true }).click()
  await page.getByLabel('Enable repository synchronization', { exact: true }).check()
  await page.getByRole('button', { name: 'Save repository source', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sync now', exact: true })).toBeEnabled()
  await page.getByLabel('Prepare again even when the commit is unchanged', { exact: true }).check()
  await page.getByRole('button', { name: 'Sync now', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Repository sync queued' })).toBeVisible()
  const history = await api.call('GET', `${path}/repository-sources/application-tests/syncs`)
  expect(history.items).toHaveLength(1)
  expect(history.items[0].data.state).toBe('received')
  expect(history.items[0].data.force).toBe(true)
  source = await api.call('GET', `${path}/repository-sources/application-tests`)
  expect(source.data.generation).toBe(3)
  expect((await api.call('GET', `${path}/runs`)).items).toEqual([])
  await page.reload()
  await page.getByRole('button', { name: 'Inspect repository Application tests', exact: true }).click()
  const table = page.getByRole('table', { name: 'Repository synchronization history', exact: true })
  await expect(table.getByRole('cell', { name: 'received', exact: true })).toBeVisible()
  await table.getByRole('button', { name: 'Inspect sync', exact: true }).click()
  await expect(page.getByRole('definition').filter({ hasText: history.items[0].id })).toBeVisible()
  await page.getByLabel('Color theme').selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
