import { test, expect, followNavigation } from './fixtures'
import pathModule from 'node:path'

test('Create tests through dedicated typed routes and review recorded browser source', { tag: '@STUDIO-CREATE-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  const newTest = `/projects/${project}/tests/new`
  await page.goto(`/projects/${project}/catalog`)
  await page.getByRole('link', { name: '+ Create test', exact: true }).click()
  await expect(page).toHaveURL(newTest)
  await expect(page.getByRole('heading', { name: 'What type of test?', exact: true })).toBeVisible()
  for (const name of ['Playwright browser test', 'HTTPS probe', 'Go suite']) await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
  await testInfo.attach('create-test-types', { body: await page.screenshot(), contentType: 'image/png' })
  await page.getByRole('link', { name: 'HTTPS probe', exact: true }).click()
  await expect(page).toHaveURL(newTest+'/https')
  await page.getByText('Advanced details', { exact: true }).click()
  await page.getByLabel('Permanent identifier', { exact: true }).fill('CREATED-PROBE')
  await page.getByLabel('Title', { exact: true }).fill('Created health probe')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Create test help', exact: true })
  await expect(help).toBeVisible()
  for (const title of ['Introduction', 'Concepts', 'Tutorials']) await expect(help.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Created health probe')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('link', { name: 'Back to catalog', exact: true }).click()
  await expect(page).toHaveURL(newTest+'/https')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Use a registered environment', { exact: true }).check()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Safety rationale', { exact: true }).fill('Reads the isolated local health endpoint')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: /^Draft changes saved\./ })).toBeVisible()
  await expect(page.getByRole('cell', { name: /Created health probe/ })).toBeVisible()

  await page.getByRole('link', { name: '+ Create test', exact: true }).click()
  await page.getByRole('link', { name: 'Playwright browser test', exact: true }).click()
  await expect(page).toHaveURL(newTest+'/playwright')
  await expect(page.getByLabel('Source ZIP', { exact: true })).toHaveCount(0)
  await page.getByLabel('Suite for this test', { exact: true }).selectOption('health')
  const recorder = page.getByRole('region', { name: 'Record a browser test', exact: true })
  await recorder.getByLabel('Recording start address', { exact: true }).fill('http://127.0.0.1:8050')
  await recorder.getByText('Advanced recording details', { exact: true }).click()
  await recorder.getByLabel('Recorded test ID', { exact: true }).fill('REC-CREATE-001')
  await recorder.getByLabel('Recorded test title', { exact: true }).fill('Recorded continuation flow')
  await recorder.getByRole('button', { name: 'Start browser recording', exact: true }).click()
  await expect(recorder.getByRole('status')).toContainText('Recording · REC-CREATE-001')
  await page.reload()
  await page.getByLabel('Suite for this test', { exact: true }).selectOption('health')
  await expect(recorder.getByRole('status')).toContainText('Recording · REC-CREATE-001')
  await recorder.getByRole('button', { name: 'Stop and keep recording', exact: true }).click()
  await expect(recorder.getByRole('status')).toContainText('Ready for review · REC-CREATE-001')
  await recorder.getByRole('button', { name: 'Review recorded test', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Playwright editor', exact: true })
  await expect(editor.getByRole('textbox', { name: 'Source code: checks/recording.spec.ts', exact: true })).toContainText('@REC-CREATE-001')
  await expect(editor).toContainText('Execution uses the selected registered environment')
  await expect(editor.getByRole('textbox', { name: 'Source code: checks/recording.spec.ts', exact: true })).toContainText('TESTSTUDIO_BASE_URL')
  await page.getByLabel('File', { exact: true }).selectOption('catalog.json')
  await expect(editor.getByRole('textbox', { name: 'Source code: catalog.json', exact: true })).toContainText('needs-review')
  await editor.getByRole('button', { name: 'Save Playwright draft', exact: true }).click()
  await expect(editor.getByRole('status').filter({ hasText: 'Draft saved at revision 1.' })).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Validate and prepare draft', exact: true })).toBeEnabled()
  await editor.getByRole('button', { name: 'Validate and prepare draft', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel preparation', exact: true }).click()
  expect((await api.call('GET', `${path}/runs`)).items).toEqual([])
  await followNavigation(page, 'Projects')
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()

  await api.call('PUT', `${path}/suites/browser-bundles`, { id: 'browser-bundles', name: 'Imported browser checks', applications: [], requiresTarget: false }, 0)
  await page.goto(newTest+'/go')
  await page.getByLabel('Suite for this test', { exact: true }).selectOption('browser-bundles')
  await expect(page.getByRole('heading', { name: 'Import a Go suite', exact: true })).toBeVisible()
  await expect(page.getByLabel('Source ZIP', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Record a browser test', exact: true })).toHaveCount(0)
  await page.goto(`/projects/${project}/sources`)
  await page.getByLabel('Suite for sources', { exact: true }).selectOption('browser-bundles')
  await page.getByLabel('Source ZIP', { exact: true }).setInputFiles(pathModule.join(__dirname, 'fixtures/bundle-browser.zip'))
  await page.getByLabel('Suite manifest path', { exact: true }).fill('suites/browser.json')
  await page.getByRole('button', { name: 'Upload and prepare bundle', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel preparation', exact: true }).click()
  await page.getByRole('button', { name: 'Edit a copy in Playwright', exact: true }).click()
  await expect(editor.getByRole('textbox', { name: 'Source code: browser/checks/greeting.spec.ts', exact: true })).toContainText('@BROWSER-UPLOAD-001')
  await expect(editor).toContainText('suites/browser.json')
  await page.getByLabel('Draft name', { exact: true }).fill('Imported editable browser source')
  await editor.getByRole('button', { name: 'Save Playwright draft', exact: true }).click()
  const saved = await api.call('GET', `${path}/suites/browser-bundles/playwright-drafts`)
  expect(saved.items[0].data.manifestPath).toBe('suites/browser.json')
  expect(saved.items[0].data.files.map((file: { path: string }) => file.path)).toContain('browser/package-lock.json')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme').selectOption('dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('recording-and-source-mobile', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
