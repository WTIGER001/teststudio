import { test, expect } from './fixtures'

test('Quick URL probes reuse protected targets or review new target configuration before local execution', { tag: '@STUDIO-URL-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await api.call('PUT', `${path}/environments/local`, { id: 'local', name: 'Protected local instance', applicationId: 'app', stage: 'local', protected: true, endpoints: { api: 'http://127.0.0.1:8040' } }, 1)
  await page.goto(`/projects/${project}/tests/new/https?suite=health`)
  const wizard = page.locator('ts-https-wizard')
  await wizard.getByLabel('Title', { exact: true }).fill('http://127.0.0.1:8040/healthz')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(wizard.getByLabel('Website URL', { exact: true })).toHaveValue('http://127.0.0.1:8040/healthz')
  await expect(wizard.getByLabel('Relative path', { exact: true })).toHaveCount(0)
  await expect(wizard).toContainText('Uses registered target Protected local instance · local · Protected')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await wizard.getByRole('button', { name: 'Save and run', exact: true }).click()
  await expect(wizard.getByRole('alert')).toContainText('This target is protected')
  expect((await api.call('GET', `${path}/tests`)).items).toHaveLength(0)
  expect((await api.call('GET', `${path}/environments`)).items).toHaveLength(1)
  await wizard.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: /^Draft changes saved/ })).toBeVisible()
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(0)
  expect((await api.call('GET', `${path}/tests`)).items[0].data.check).toMatchObject({ endpoint: 'api', path: '/healthz' })

  const emptyProject = `url-${Date.now()}`, emptyPath = `/api/v1/projects/${emptyProject}`
  await api.call('POST', '/api/v1/projects', { id: emptyProject, name: 'Quick URL checks' })
  await api.call('PUT', `${emptyPath}/applications/app`, { id: 'app', name: 'Website' }, 0)
  await api.call('PUT', `${emptyPath}/suites/quick`, { id: 'quick', name: 'Quick checks', applications: ['app'], requiresTarget: true }, 0)
  await page.goto(`/projects/${emptyProject}/tests/new/https?suite=quick`)
  await wizard.getByLabel('Title', { exact: true }).fill('Quick website availability')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await wizard.getByLabel('Website URL', { exact: true }).fill('htttps://127.0.0.1:8040/healthz')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(wizard.getByRole('alert')).toContainText('Enter a complete HTTP or HTTPS URL')
  await expect(wizard.getByLabel('Website URL', { exact: true })).toBeFocused()
  await wizard.getByLabel('Website URL', { exact: true }).fill('http://127.0.0.1:8040/healthz?quick=1')
  await wizard.getByText('Advanced target options', { exact: true }).click()
  await wizard.getByLabel('Target stage', { exact: true }).selectOption('local')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  const configuration = wizard.getByRole('region', { name: 'Target configuration to save', exact: true })
  await expect(configuration).toContainText('A new application will also be created')
  await expect(configuration).toContainText('http://127.0.0.1:8040')
  expect((await api.call('GET', `${emptyPath}/applications`)).items).toHaveLength(0)
  expect((await api.call('GET', `${emptyPath}/environments`)).items).toHaveLength(0)
  await wizard.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(wizard.getByLabel('Website URL', { exact: true })).toHaveValue('http://127.0.0.1:8040/healthz?quick=1')
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Color theme').selectOption('dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('quick-url-review', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await wizard.getByRole('button', { name: 'Save and run', exact: true }).click()
  const results = page.getByRole('region', { name: 'Final test results', exact: true })
  await expect(results.getByRole('cell', { name: 'passed', exact: true })).toBeVisible({ timeout: 20000 })
  const applications = (await api.call('GET', `${emptyPath}/applications`)).items
  const environments = (await api.call('GET', `${emptyPath}/environments`)).items
  expect(applications).toHaveLength(1); expect(environments).toHaveLength(1)
  expect(environments[0].data).toMatchObject({ applicationId: applications[0].id, stage: 'local', protected: false, endpoints: { api: 'http://127.0.0.1:8040' } })
  expect((await api.call('GET', `${emptyPath}/tests`)).items[0].data.check.path).toBe('/healthz?quick=1')
  expect((await api.call('GET', `${emptyPath}/suites`)).items[0].data.activeReleaseId || '').toBe('')
})
