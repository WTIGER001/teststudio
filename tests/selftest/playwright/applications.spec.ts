import { test, expect, followNavigation } from './fixtures'

test('Applications navigation exposes environments and linked suite workflows', { tag: '@STUDIO-APPS-001' }, async ({ page, api }, testInfo) => {
  const { project, path } = await api.scaffold()
  await page.goto(`/projects/${project}/catalog`)
  await followNavigation(page, 'Applications')
  await expect(page).toHaveURL(`/projects/${project}/applications`)
  await expect(page.getByRole('heading', { name: 'Applications', exact: true })).toBeVisible()
  const navigation = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  await expect(navigation.getByRole('link', { name: 'Applications', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('link', { name: 'Open application TestStudio', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Environments', exact: true })).toContainText('Self-test instance')
  await expect(page.getByRole('region', { name: 'Linked suites', exact: true })).toContainText('Health checks')
  await page.getByRole('link', { name: 'View tests in Health checks', exact: true }).click()
  await expect(page.getByLabel('Filter by suite', { exact: true })).toHaveValue('health')
  await followNavigation(page, 'Applications')
  await page.getByRole('button', { name: '+ Add application', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Parcel desk')
  await page.getByLabel('Permanent identifier', { exact: true }).fill('parcel')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page).toHaveURL(`/projects/${project}/applications/parcel`)
  await expect(page.getByRole('heading', { name: 'Parcel desk', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Environments', exact: true })).not.toContainText('Self-test instance')
  await page.getByRole('button', { name: 'Add environment', exact: true }).click()
  await expect(page.getByLabel('Application', { exact: true })).toHaveValue('parcel')
  await expect(page.getByLabel('Application', { exact: true })).toBeDisabled()
  await page.getByLabel('Name', { exact: true }).fill('Parcel development')
  await page.getByLabel('Permanent identifier', { exact: true }).fill('parcel-dev')
  await page.getByLabel('Endpoint URL', { exact: true }).fill('https://parcel.example.test')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Environments', exact: true })).toContainText('Parcel development')
  await page.getByRole('button', { name: 'Add suite', exact: true }).click()
  await expect(page.getByLabel('Application (optional)', { exact: true })).toHaveValue('parcel')
  await page.getByLabel('Name', { exact: true }).fill('Parcel browser checks')
  await page.getByLabel('Permanent identifier', { exact: true }).fill('parcel-checks')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  const suites = page.getByRole('region', { name: 'Linked suites', exact: true })
  await expect(suites).toContainText('Parcel browser checks')
  await suites.getByRole('link', { name: 'Create test', exact: true }).click()
  await page.getByRole('link', { name: 'Playwright browser test', exact: true }).click()
  await expect(page.getByLabel('Suite for this test', { exact: true })).toHaveValue('parcel-checks')
  await page.goto(`/projects/${project}/applications/parcel`)
  await page.getByRole('button', { name: 'Add environment', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Unsaved environment')
  page.once('dialog', dialog => dialog.dismiss())
  await followNavigation(page, 'Test catalog')
  await expect(page).toHaveURL(`/projects/${project}/applications/parcel`)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Cancel registration', exact: true }).click()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Applications help', exact: true })
  for (const name of ['Introduction', 'Concepts', 'Tutorials']) await expect(help.getByRole('heading', { name, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByLabel('Color theme').selectOption('dark')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await testInfo.attach('application-detail-mobile-dark', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  expect((await api.call('GET', `${path}/environments`)).items.find((row: any) => row.id === 'parcel-dev').data.applicationId).toBe('parcel')
  expect((await api.call('GET', `${path}/suites`)).items.find((row: any) => row.id === 'parcel-checks').data.applications).toEqual(['parcel'])
  const restricted: string[] = []
  await page.route(`**/api/v1/me/capabilities?project=${project}`, async route => { const response = await route.fetch(); const body = await response.json(); body['teststudio.environments.read'] = false; body['teststudio.suites.read'] = false; await route.fulfill({ response, json: body }) })
  page.on('request', request => { if ([`${path}/environments`, `${path}/suites`].some(suffix => new URL(request.url()).pathname === suffix)) restricted.push(request.url()) })
  await page.goto(`/projects/${project}/applications/parcel`)
  await expect(page.getByRole('heading', { name: 'Parcel desk', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Environments', exact: true })).toContainText('Environment read permission is required')
  expect(restricted).toEqual([])
  const second = await api.scaffold()
  await page.goto(`/projects/${second.project}/applications`)
  await expect(page.getByRole('link', { name: 'Open application TestStudio', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Parcel desk', exact: true })).toHaveCount(0)
})
