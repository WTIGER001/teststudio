import { test, expect, expectHTTPFailure } from './fixtures'

test('suite settings, revision conflicts, archive and restoration retain history and schedule pins', { tag: '@STUDIO-SUITES-001' }, async ({ page, api }) => {
  const { project, path } = await api.scaffold()
  await api.createCheck(path)
  const run = await api.run(path)
  await api.call('POST', `${path}/schedules`, { id: 'suite-pin', name: 'Pinned suite history', enabled: false, kind: 'interval', intervalSeconds: 60, request: { suiteId: 'health', environmentId: 'local', releaseId: run.release.id, timeoutSeconds: 60 } })
  await page.goto(`/projects/${project}/configuration`)
  await page.getByRole('button', { name: /^Suites / }).click()
  await page.getByRole('button', { name: 'Inspect suite Health checks', exact: true }).click()
  const manager = page.getByRole('region', { name: 'Suite settings', exact: true })
  await expect(manager.getByRole('table', { name: 'Schedules that reference this suite', exact: true })).toContainText('Pinned suite history')
  await expect(manager).toContainText(run.release.id)
  await manager.getByLabel('Suite name', { exact: true }).fill('Reviewed availability')
  await manager.getByLabel('Suite description', { exact: true }).fill('Retain the published execution history')
  await manager.getByRole('button', { name: 'Save suite settings', exact: true }).click()
  await expect(manager.getByRole('status')).toContainText('Suite settings saved')
  await expect(page.getByRole('button', { name: 'Inspect suite Reviewed availability', exact: true })).toBeVisible()
  const state = await api.call('GET', `${path}/suites/health/lifecycle`)
  await api.call('PATCH', `${path}/suites/health/settings`, { name: 'Concurrent suite name', description: state.suite.description, applications: ['app'], requiresTarget: true }, state.revision)
  await manager.getByLabel('Suite description', { exact: true }).fill('Unsaved description after a concurrent edit')
  await expectHTTPFailure(page, 'PATCH', `${path}/suites/health/settings`, 409, () => manager.getByRole('button', { name: 'Save suite settings', exact: true }).click())
  await expect(manager.getByRole('alert')).toContainText('Reload suite settings')
  await expect(manager.getByRole('button', { name: 'Archive suite', exact: true })).toBeDisabled()
  await manager.getByRole('button', { name: 'Reload suite settings', exact: true }).click()
  await expect(manager.getByLabel('Suite name', { exact: true })).toHaveValue('Concurrent suite name')
  await manager.getByRole('button', { name: 'Archive suite', exact: true }).click()
  await expect(manager.getByRole('status')).toContainText('Suite archived')
  await expect(manager.getByLabel('Suite name', { exact: true })).toBeDisabled()
  await expect(manager.getByRole('table', { name: 'Schedules that reference this suite', exact: true })).toContainText(run.release.id)
  await manager.getByRole('link', { name: 'Suite version history', exact: true }).click()
  await expect(page.getByText('This suite is archived. Its versions remain readable. Restore the suite before activation.', { exact: true })).toBeVisible()
  await page.goto(`/projects/${project}/configuration`)
  await page.getByRole('button', { name: /^Suites / }).click()
  await page.getByRole('button', { name: 'Inspect suite Concurrent suite name', exact: true }).click()
  await manager.getByRole('button', { name: 'Restore suite', exact: true }).click()
  await expect(manager.getByRole('status')).toContainText('Suite restored')
  await expect(manager.getByLabel('Suite name', { exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Project settings help', exact: true })
  await expect(help.getByText('Suite lifecycle', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  expect((await api.call('GET', `${path}/runs/${run.id}`)).data.release.id).toBe(run.release.id)
  expect((await api.call('GET', `${path}/schedules/suite-pin`)).data.request.releaseId).toBe(run.release.id)
  expect((await api.call('GET', `${path}/runs`)).items).toHaveLength(1)
  expect((await api.call('GET', `${path}/runs/${run.id}/artifacts`)).items.length).toBeGreaterThan(0)
})
